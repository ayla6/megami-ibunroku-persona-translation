EVT_TABLES = [(0x800D0CB8, 0x800D0F30)]     # (pointer, speaker) pairs
_ADDRS = os.path.join(ROOT, 'src', 'asm', 'common', 'addresses.inc')


_EQUS = None


def _equ(name, _seen=()):
    """One number from the assembler's OWN file - expressions included, since
    a bank's address is written as one (BTLEVT_SPILL_ADDR equ SLPS_TAILS_ADDR +
    SLPS_TAILS_SIZE). The build, the porters and the asm read the same
    constant, because a buffer size and a spill address are not guesses."""
    global _EQUS
    if _EQUS is None:
        _EQUS = {}
        for m in re.finditer(r'^\s*([A-Z][A-Z0-9_]*)\s+equ\s+([^;\n]+)',
                             open(_ADDRS).read(), re.M):
            _EQUS[m.group(1)] = m.group(2).strip()
    if name in _seen:
        toolbelt.fail(f'btlp: {name} is defined in terms of itself')
    if name not in _EQUS:
        toolbelt.fail(f'btlp: {name} is not in common/addresses.inc')
    expr = re.sub(r'(?<![0-9A-Za-z_$])[A-Z][A-Z0-9_]*',   # not the FF00 of 0xFF00
                  lambda m: str(_equ(m.group(0), _seen + (name,))), _EQUS[name])
    try:
        return int(eval(expr, {'__builtins__': {}}, {}))
    except Exception:
        toolbelt.fail(f'btlp: {name} = {_EQUS[name]!r} is not a number')


# Text and unpacker share the original zone, but each owns a disjoint part.
# Read both boundaries from the same assembly constants; never let the clear
# include executable code or its generated byte-pair table.
EVT_ZONE = (_equ('BTLEVT_ZONE_START'), _equ('BTLEVT_ZONE_END'))
EVT_UNPACK = _equ('BTLEVT_UNPACK_ADDR')
EVT_TAIL = EVT_ZONE[1] - EVT_UNPACK
if not EVT_ZONE[0] < EVT_UNPACK < EVT_ZONE[1]:
    toolbelt.fail('btlp: invalid battle text/unpacker ownership boundaries')

# the drawn string's buffer, and the resident bank an over-slot message's text
# lives in (see evt_plan: a slot may hold a pointer instead of its string)
EVT_BUF = _equ('BTLEVT_BUF_SIZE')
EVT_MARK = _equ('BTLEVT_MARK')              # 'FF 00' + big-endian address
EVT_MARK_LEN = 6
EVT_OUT = os.path.join(ROOT, 'build', 'btlevt.asm')
EVT_OUT_PAIRS = os.path.join(ROOT, 'build', 'btlevt_pairs.asm')
EVT_OUT_SLPS = os.path.join(ROOT, 'build', 'btlevt_slps.asm')
EVT_CODES = list(range(0x01, 0x88)) + list(range(0xEA, 0xFF))  # never 88-E9, never FF
EVT_ALIGN = 2
# the spill homes: strings whose own slot could not hold them live in dead
# SLPS fragments (deadfuncs.py 16 - the only build-time homes left in the
# image; see addresses.inc BTLEVT_SPILL_*). The drawn string's unpack buffer
# is separate runtime scratch (BTLEVT_BUF_ADDR, the game's wiped BSS).
EVT_SPILL = [(_equ('BTLEVT_SPILL_ADDR'), _equ('BTLEVT_SPILL_END')),
             (_equ('BTLEVT_SPILL2_ADDR'), _equ('BTLEVT_SPILL2_END')),
             (_equ('BTLEVT_SPILL3_ADDR'), _equ('BTLEVT_SPILL3_END')),
             (_equ('BTLEVT_SPILL4_ADDR'), _equ('BTLEVT_SPILL4_END'))]


def evt_messages(d):
    out = []
    p = EVT_ZONE[0]
    while p < EVT_ZONE[1]:
        if d[p - B] == 0:
            p += 1
            continue
        e = d.index(END, p - B) + 2 + B
        out.append((p, e))
        p = e
    return out


def _mips_gpr_write(word):
    """Written GPR index, 0 for none, or None for an unclassified instruction.

    Decode only R3000 instruction forms; an unknown word clears provenance
    instead of allowing a speculative text relocation across it.
    """
    op = word >> 26
    rs, rt, rd, fn = (word >> 21) & 31, (word >> 16) & 31, (word >> 11) & 31, word & 63
    if op == 0:
        if fn in (0x08, 0x11, 0x13, 0x18, 0x19, 0x1a, 0x1b):
            return 0  # jr, mthi/mtlo, mult/div
        if fn in (0x0c, 0x0d):
            return None  # syscall/break may have arbitrary effects
        if fn in (0x00, 0x02, 0x03, 0x04, 0x06, 0x07, 0x09, 0x10, 0x12,
                  0x20, 0x21, 0x22, 0x23, 0x24, 0x25, 0x26, 0x27, 0x2a, 0x2b):
            return rd
        return None
    if op == 1:
        return 31 if rt in (16, 17) else 0
    if op == 3:
        return 31  # jal
    if op in (2, 4, 5, 6, 7, 0x28, 0x29, 0x2a, 0x2b, 0x2e, 0x32, 0x3a):
        return 0  # branches, stores, COP2 memory operations
    if op in (*range(8, 16), 0x20, 0x21, 0x22, 0x23, 0x24, 0x25, 0x26):
        return rt  # ALU-immediate or GPR load
    if op in (0x10, 0x12):
        return rt if rs in (0, 2) else 0  # mfc/cfc; other COP operations
    return None


def _mips_control(word):
    op = word >> 26
    return (op in (1, 2, 3, 4, 5, 6, 7)
            or (op == 0 and (word & 63) in (8, 9))
            or (op in (0x10, 0x12) and ((word >> 21) & 31) == 8))


def _zone_refs(d, zone, tables=None, lui_age=None):
    """{ram address: [('word'|'addiu', where)]} for addresses inside zone"""
    found = {}
    for o in range(0, len(d) - 3, 4):
        w = struct.unpack_from('<I', d, o)[0]
        if zone[0] <= w < zone[1] and (
                tables is None or any(t0 <= B + o < t1 for t0, t1 in tables)):
            found.setdefault(w, []).append(('word', B + o))
    if capstone is None:
        toolbelt.fail('btlp: capstone is required (pip install capstone)')
    # A direct entry into a LUI/ADDIU sequence can bypass the LUI. Treat even
    # targets decoded from non-code as hazards rather than speculating that a
    # word is data; indirect entries still need independent ownership evidence.
    targets = set()
    for o in range(0, len(d) - 3, 4):
        word = struct.unpack_from('<I', d, o)[0]
        op, pc = word >> 26, B + o
        if op in (1, 4, 5, 6, 7) or (op in (0x10, 0x12) and (word >> 21) & 31 == 8):
            displacement = word & 0xffff
            if displacement & 0x8000:
                displacement -= 0x10000
            targets.add((pc + 4 + (displacement << 2)) & 0xffffffff)
        elif op in (2, 3):
            targets.add(((pc + 4) & 0xf0000000) | ((word & 0x03ffffff) << 2))
    age = lui_age if lui_age is not None else 3
    hiv = {}
    delay = False
    pending_load = 0
    for o in range(0, len(d) - 3, 4):
        word = struct.unpack_from('<I', d, o)[0]
        op, rs, rt = word >> 26, (word >> 21) & 31, (word >> 16) & 31
        hiv = {r: (v, n + 1, origin) for r, (v, n, origin) in hiv.items() if n < age}
        if delay and op == 15 and rt:
            high = (word & 0xffff) << 16
            if high - 0x8000 < zone[1] and high + 0x7fff >= zone[0]:
                toolbelt.fail(f'btlp: ambiguous text-bank LUI in branch delay slot at {B + o:#x}')
        if op == 9 and rs in hiv:  # addiu, before invalidating its destination
            imm = word & 0xffff
            if imm & 0x8000:
                imm -= 0x10000
            v = (hiv[rs][0] + imm) & 0xffffffff
            if zone[0] <= v < zone[1]:
                origin = hiv[rs][2]
                if any(at in targets for at in range(origin + 4, B + o + 1, 4)):
                    toolbelt.fail(f'btlp: branch can bypass LUI for text reference at {B + o:#x}')
                found.setdefault(v, []).append(('addiu', B + o))
        # R3000 loads write one instruction later: the immediately following
        # instruction still reads the old register. A consecutive load into
        # the same register cancels the first delayed write, so its old value
        # remains available for one more instruction.
        written = _mips_gpr_write(word)
        load = (op in (0x20, 0x21, 0x22, 0x23, 0x24, 0x25, 0x26)
                or (op in (0x10, 0x12) and rs in (0, 2)))
        if pending_load and not (load and written == pending_load):
            hiv.pop(pending_load, None)
        if written is None:
            hiv.clear()
        elif written and not load:
            hiv.pop(written, None)
        if delay:
            hiv.clear()  # after the delay slot, a new control-flow block
        elif op == 15 and rt:
            hiv[rt] = ((word & 0xffff) << 16, 0, B + o)
        pending_load = written if load and written else 0
        delay = _mips_control(word)
    return found


def evt_refs(d):
    return _zone_refs(d, EVT_ZONE, tables=EVT_TABLES, lui_age=3)


def laid(t):
    """A BTLP box breaks on <FFF6> - the PSX battle line move. PSP wording
    carries its own line break as <FF03> (the ADV code); the port's reflow
    turns one into the other, but a wording that already fits keeps its
    codes verbatim. The family builder is the authority on what the box
    breaks on, so the break is normalised once, here, for every dialogue
    family: this is layout, never wording."""
    return t.replace('<FF03>', '<FFF6>')


def dec(d, a, e):
    """dialogue-encoding text of [a, e) (shared by all FFF5 families)"""
    out, i = [], a - B
    while i < e - B:
        c = d[i]
        if c == 0xFF:
            if d[i + 1] != 0xF5:
                out.append('<FF%02X>' % d[i + 1])
            i += 2
        elif 0x80 <= c <= 0x87:
            out.append(etext.glyph.get(((c & 7) << 8) | d[i + 1], '<G%03X>' % (((c & 7) << 8) | d[i + 1])))
            i += 2
        else:
            out.append(etext.glyph.get(c, '<G%02X>' % c))
            i += 1
    return ''.join(out)


def codes(b, free=()):
    """control codes as a sorted multiset (two-byte glyphs 80-87 xx
    skipped). `free` names the layout codes the English may re-shape when
    it is rewrapped: the evt family frees FFF6 newlines (the proven
    btlevt rule - 'newlines may move when the English is rewrapped'),
    msg/neg keep the Japanese break structure exactly."""
    out, i = [], 0
    while i < len(b) - 1:
        if b[i] == 0xFF:
            c = b[i + 1]
            out.append(c)
            i += 2 + 2 * E_PARAM_UNITS.get(c, 0)   # params belong to their code
        elif 0x80 <= b[i] <= 0x87:
            i += 2
        else:
            i += 1
    return sorted(c for c in out if c not in free)


def evt_original_layout(raw):
    """Retain untranslated Japanese, spelling an inserted speaker label inline.

    An insertion immediately followed by the original colon at the start of a
    battle message is a speaker label. The label/body gap is layout, not a
    translation: add one VWF space only when the body has visible content and
    no spacing already. Insert codes are the renderer's decomp-derived set.
    """
    if len(raw) < 4 or raw[0] != 0xFF or raw[1] not in vwf_wrap.BTL_NAME_INSERT_CODES:
        return raw
    for colon in (etext.encode('：', end=None), etext.encode(':', end=None)):
        head = 2 + len(colon)
        if raw[2:head] != colon or head >= len(raw):
            continue
        # No visible next glyph, or the source already carries a gap.
        if raw[head] in (0x00, 0x88, 0xFF):
            return raw
        return raw[:head] + etext.encode(' ', end=None) + raw[head:]
    return raw


def evt_plan(d, rows_by_pos):
    """Decide the whole evt family once: each message's PACKED bytes, where
    they go, which slot hands its text over to a pointer, and why a message
    cannot ship.

    This is the family's ONE placement rule, and a porter asks it directly
    (evt_accept) instead of guessing: 'the English is more bytes than the
    slot' does not make a row a draft, because a slot nothing re-points still
    only has to hold 'FF 00 hi lo' - the unpacker follows that pointer into
    the resident spill bank, where a message's length is nobody's budget."""
    msgs = evt_messages(d)
    rf = evt_refs(d)
    new, refused = {}, {}
    for i, (a, e) in enumerate(msgs):
        r = rows_by_pos.get(hex(a - B))
        t = laid((r['en'] if r else '').strip())
        if not etext.has_text(t):
            # Its original reference still exists. Pack and relocate the
            # original bytes too: otherwise clearing/repacking the zone would
            # leave it pointing into someone else's text or zero padding.
            new[i] = evt_original_layout(bytes(d[a - B:e - B]))
            continue
        try:
            b = etext.encode(t, end=END)
        except ValueError as ex:
            toolbelt.fail(f'evt {i} {t!r}: {ex}')
        orig = bytes(d[a - B:e - B])
        pages = re.split(r'<FFFB><FFF7>|<FF04>', t)
        for pi, page in enumerate(pages):
            lines = page.split('<FFF6>')
            if len(lines) > 4:
                # three visible lines + the fourth scroll line. The
                # interpreter waits when the 3x15-cell window fills; a
                # fifth line would need a second scroll and is outside the
                # page model. The Japanese ships for a page that needs more.
                print(f'btlp: evt {i}: a page has {len(lines)} lines (max 4) '
                      f'- overflow, Japanese ships')
                b = orig
                break
            for li, ln in enumerate(lines):
                w = vwf_wrap.text_width(ln)
                # the flow's own contract (vwf_wrap.flow_lines): a line may
                # reach the pen's 240 only when it holds the last word of the
                # whole stream - never directly before an explicit break
                last = (pi == len(pages) - 1 and li == len(lines) - 1)
                if w > (240 if last else 239):
                    toolbelt.fail(f'evt {i} line {ln!r} is {w} px wide '
                                  f'(max {240 if last else 239})')
        new[i] = b
    plan = {'msgs': msgs, 'rf': rf, 'new': new, 'packed': {}, 'place': {},
            'marker': {}, 'spill': {}, 'refused': refused, 'pairs': []}
    if not new:
        return plan
    for i, b in new.items():
        if len(b) > EVT_BUF:
            toolbelt.fail(f'evt {i} is {len(b)} bytes unpacked (buffer {EVT_BUF})')

    # the ONE packer (bpe), not a copy of it: the format is decided in
    # exactly two places - bpe and btlp/btlevt_unpack.asm - and this
    # family only says which strings to pack. bpe.pack walks the code
    # parameters exactly like the decoder and verifies every string
    # round-trips through its own mirror of the unpacker.
    packed, pairs = bpe.pack(dict(new))
    plan['packed'], plan['pairs'] = packed, pairs

    fixed = {i for i in packed if not rf.get(msgs[i][0])}
    free = [[EVT_ZONE[0], EVT_ZONE[1] - EVT_TAIL]]
    spill = [list(z) for z in EVT_SPILL]
    place = plan['place']
    spilled = plan['spill']

    def take(zones, n, best=False):
        """First free home that fits, or - with `best` - the SMALLEST one.
        The zone is a jigsaw of fixed slots, so filling a large message's
        home with a small one first leaves slivers nothing else can use: a
        50-byte line had nowhere to go while 83 bytes were free."""
        hit, left = None, None
        for z in zones:
            q = (z[0] + EVT_ALIGN - 1) & ~(EVT_ALIGN - 1)
            if q + n > z[1]:
                continue
            if not best:
                z[0] = q + n
                return q
            if left is None or z[1] - q < left:
                hit, left = (q, z), z[1] - q
        if hit is None:
            return None
        q, z = hit
        z[0] = q + n
        return q

    def carve(a, e):
        out = []
        for z in free:
            if e <= z[0] or a >= z[1]:
                out.append(z)
            else:
                if z[0] < a:
                    out.append([z[0], a])
                if e < z[1]:
                    out.append([e, z[1]])
        free[:] = out

    for i in sorted(fixed):
        a, e = msgs[i]
        if len(packed[i]) > e - a:
            # THE SLOT IS NOT THE TEXT. It only has to say where the text is,
            # so its size stops bounding the wording: write FF 00 <address>
            # there and let the unpacker follow it into the spill bank.
            q = take(spill, len(packed[i])) if e - a >= EVT_MARK_LEN else None
            if q is None:
                toolbelt.fail(f'evt {i}: packed message does not fit its '
                              f'{e - a}-byte fixed slot and spill is full')
            else:
                plan['marker'][i] = q
                plan['spill'][q] = packed[i]
                # FF 00 + the address as two halfwords in the order lhu reads
                # them (btl_unpack_chain: lhu 2, lhu 4, sll 16, or)
                packed[i] = (struct.pack('<H', EVT_MARK)
                             + struct.pack('<HH', q >> 16, q & 0xFFFF))
        if e > EVT_ZONE[1] - EVT_TAIL:
            toolbelt.fail(f'evt fixed message {i} overlaps the unpacker tail')
        place[i] = a
        carve(a, a + len(packed[i]))
    code = [i for i in packed if i not in fixed and any(k == 'addiu' for k, _ in rf.get(msgs[i][0], []))]
    words = [i for i in packed if i not in fixed and i not in code]
    # LARGEST FIRST, SMALLEST HOME THAT FITS: the placement is nobody's
    # structure (every reference is repointed at wherever the string lands),
    # so it can be the packing that wastes the least.
    for i in sorted(code, key=lambda i: -len(packed[i])):
        place[i] = take(free, len(packed[i]), best=True)
        if place[i] is None:
            toolbelt.fail(f'evt: out of space in the BTLP zone at message {i}')
    gone = []
    for i in sorted(words, key=lambda i: -len(packed[i])):
        place[i] = take(free, len(packed[i]), best=True)
        if place[i] is None:
            place[i] = take(spill, len(packed[i]), best=True)
            gone.append(i)
            if place[i] is None:
                toolbelt.fail(f'evt {i}: no room for packed message in the '
                              f'battle text zone or spill bank')
            # a string this family RELOCATED lives in the spill bank; its
            # bytes are written by the same include that carries the marker
            # texts (btlevt_slps.asm), so keep it out of the zone emission
            plan['spill'][place[i]] = packed[i]
    return plan


def evt_build(d, rows_by_pos, body):
    plan = evt_plan(d, rows_by_pos)
    packed, place = plan['packed'], plan['place']
    if not packed:
        toolbelt.write_asm(EVT_OUT_SLPS, 'btlp', '')   # the include is permanent
        return 0
    pairs, msgs, rf = plan['pairs'], plan['msgs'], plan['rf']
    with open(EVT_OUT_PAIRS, 'w', newline=NL) as o:
        o.write(';; byte pairs of the pair codes 01..87, EA..FE (in this order)\n')
        for x, y in pairs:
            o.write(f'    .byte {x:#04x}, {y:#04x}\n')
    body.append(f'.org {EVT_ZONE[0]:#x}\n    .fill {EVT_UNPACK - EVT_ZONE[0]:#x}, 0')
    banked = set(plan['spill'])      # those bytes are the SLPS include's job
    for i in packed:
        if place[i] in banked:
            continue                 # a relocated string, not an overlay address
        body.append(f'.org {place[i]:#x}\n    .byte ' + ', '.join(f'0x{c:02X}' for c in packed[i]))
    for i in packed:
        a, e = msgs[i]
        for kind, where in rf.get(a, []):
            if kind == 'word':
                body.append(f'.org {where:#x}\n    .word {place[i]:#x}')
            else:
                body.append(f'.org {where:#x}\n    .halfword {place[i] & 0xFFFF:#x}')
    # texts that do not live in a slot of their own: a relocated string, and
    # the real text of a slot that only carries a pointer
    spill = plan['spill']
    toolbelt.write_asm(EVT_OUT_SLPS, 'btlp',
                       '\n'.join(f'.org {q:#x}\n    .byte '
                                 + ', '.join(f'0x{c:02X}' for c in b)
                                 for q, b in sorted(spill.items())) + '\n')
    translated = sum(bool(etext.has_text(laid((rows_by_pos.get(hex(a - B), {}).get('en') or '').strip())))
                     for a, _e in msgs)
    print(f'btlp evt: {len(pairs)} pair codes, '
          f'{sum(len(b) for i, b in plan['new'].items() if i not in plan['refused'])} -> '
          f'{sum(len(b) for i, b in packed.items() if i not in plan['refused'])} bytes, '
          f'{len(packed)}/{len(msgs)} packed ({translated} translated), '
          f'{len(plan['marker'])} slot(s) carry a pointer, {len(spill)} in the spill bank')
    return len(packed)


def evt_accept(d, rows_by_pos):
    """{pos: (ok, reason)} for a row set a PORTER is considering, decided by
    the family's own placement (evt_plan): a row that ships with a pointer in
    its slot is not over budget, and no row is promised that the build would
    keep Japanese."""
    plan = evt_plan(d, rows_by_pos)
    out = {}
    for i, (a, e) in enumerate(plan['msgs']):
        pos = hex(a - B)
        if pos not in rows_by_pos:
            continue
        out[pos] = (False, plan['refused'].get(i, '')) if i in plan['refused'] \
            else (True, '')
    return out


# ===========================================================================
# family: msg (message box)
# ===========================================================================

MSG_ZONE = (0x800D1D4C, 0x800D222C)
MSG_OUT = os.path.join(ROOT, 'build', 'btlmsg.asm')
MSG_OUT_SLPS = os.path.join(ROOT, 'build', 'btlmsg_slps.asm')
MSG_SPILL = [(0x8002E048, 0x8002E0C0), (0x80030A6C, 0x80030AD4),
             (0x800182B4, 0x8001831C)]   # dead SLPS functions (deadfuncs.py),
                                        # unreferenced by any disc binary
MSG_ALIGN = 2


def msg_script(text):
    """Translate a terminal PSP wait to the battle caller's own end wait.

    FF02 and FF05 are not BTLP controls: retail renders their operands as
    glyphs. A terminal PSP wait belongs to the end, and the original FFF5
    uses the battle caller's wait flag. Interior waits/pages have no proved
    equivalent here and must never be silently removed.
    """
    text = laid(text)
    text = re.sub(r'(?:<FF02>|<FF05><[0-9A-Fa-f]{2}><[0-9A-Fa-f]{2}>)(?=(?:<FF01>)?\s*$)', '', text)
    if re.search(r'<FF0[245]>', text):
        raise ValueError('unsupported nonterminal or malformed PSP wait/page in battle message')
    return text


def msg_build(d, rows_by_pos, body):
    msgs = []
    p = MSG_ZONE[0]
    while p < MSG_ZONE[1]:
        if d[p - B] == 0:
            p += 1
            continue
        e = d.index(END, p - B) + 2 + B
        msgs.append((p, e))
        p = e
    rf = _zone_refs(d, MSG_ZONE)
    new = {}
    translated = 0
    for i, (a, e) in enumerate(msgs):
        r = rows_by_pos.get(hex(a - B))
        t = laid((r['en'] if r else '').strip())
        orig = bytes(d[a - B:e - B])
        if not t:
            new[i] = orig
            continue
        translated += 1
        try:
            t = msg_script(t)
            b = etext.encode(t, end=END)
        except ValueError as ex:
            toolbelt.fail(f'msg {i} {t!r}: {ex}')
        if codes(b) != codes(orig):
            pass        # a code difference is not a rendering problem
        # A BOX'S WIDTH IS ITS WIDEST LINE, never the sum of its lines. This
        # family breaks a message with <FF03> (row) and <FF02> (page) and the
        # battle engine with <FFF6>, so a two-line message legitimately prices
        # wider than one line's 239 and a whole-string total refuses wording
        # the box draws fine. (The evt family has always priced per line -
        # evt_plan - and this is the same rule.)
        segs = re.split(r'<FF0[23]>|<FFF6>', t)
        for li, seg in enumerate(segs):
            cap = 240 if li == len(segs) - 1 else 239
            w = vwf_wrap.text_width(seg)
            if w > cap:
                toolbelt.fail(f'msg {i} line {seg!r} is {w} px wide (max {cap})')
        new[i] = b
    fixed = {i for i, (a, e) in enumerate(msgs) if a not in rf}
    free = [list(MSG_ZONE)]
    spill = [list(z) for z in MSG_SPILL]
    place = {}

    def take(zones, n):
        for z in zones:
            q = (z[0] + MSG_ALIGN - 1) & ~(MSG_ALIGN - 1)
            if q + n <= z[1]:
                z[0] = q + n
                return q
        return None

    def carve(a, e):
        out = []
        for z in free:
            if e <= z[0] or a >= z[1]:
                out.append(z)
            else:
                if z[0] < a:
                    out.append([z[0], a])
                if e < z[1]:
                    out.append([e, z[1]])
        free[:] = out

    for i in fixed:
        a, e = msgs[i]
        # A message with no re-pointable reference keeps its ADDRESS (the
        # code reaches it structurally). Its LENGTH is not the old slot's
        # though: wording is never the Japanese's size, and every row
        # around it IS re-pointable and moves out of the way. So it grows
        # at its own address into whatever is free there, and only wording
        # that has nowhere to go ships Japanese.
        n = len(new[i])
        if not any(z[0] <= a and a + n <= z[1] for z in free):
            new[i] = bytes(d[a - B:e - B])   # keep the Japanese as-is
            place[i] = a
            print(f'btlp: msg {i}: no room at its fixed address for {n} bytes'
                  f' - overflow, Japanese ships')
            continue
        place[i] = a
        carve(a, a + n)
    code = [i for i in range(len(msgs)) if i not in fixed and any(k == 'addiu' for k, _ in rf.get(msgs[i][0], []))]
    words = [i for i in range(len(msgs)) if i not in fixed and i not in code]
    for i in code:
        place[i] = take(free, len(new[i]))
        if place[i] is None:
            a, e = msgs[i]
            place[i], new[i] = a, bytes(d[a - B:e - B])
            print(f'btlp: msg {i}: out of space - overflow, Japanese ships')
    spilled = []
    for i in words:
        place[i] = take(free, len(new[i]))
        if place[i] is None:
            place[i] = take(spill, len(new[i]))
            spilled.append(i)
            if place[i] is None:
                a, e = msgs[i]
                place[i], new[i] = a, bytes(d[a - B:e - B])
                print(f'btlp: msg {i}: out of space (spill full) - '
                      f'overflow, Japanese ships')
    body.append(f'.org {MSG_ZONE[0]:#x}\n    .fill {MSG_ZONE[1] - MSG_ZONE[0]:#x}, 0')
    for i in range(len(msgs)):
        if i not in spilled:
            body.append(f'.org {place[i]:#x}\n    .byte ' + ', '.join(f'0x{c:02X}' for c in new[i]))
    for i, (a, e) in enumerate(msgs):
        for kind, where in rf.get(a, []):
            if kind == 'word':
                body.append(f'.org {where:#x}\n    .word {place[i]:#x}')
            else:
                body.append(f'.org {where:#x}\n    .halfword {place[i] & 0xFFFF:#x}')
    if spilled:
        toolbelt.write_asm(MSG_OUT_SLPS, 'btlp',
                           ';; battle messages spilled into dead SLPS functions\n'
                           + '\n'.join(f'.org {place[i]:#x}\n    .byte '
                                       + ', '.join(f'0x{c:02X}' for c in new[i])
                                       for i in spilled) + '\n')
    print(f'btlp msg: {translated}/{len(msgs)} translated, {len(spilled)} spilled')
    return translated


# ===========================================================================
# family: neg (negotiation / CONTACT)
# ===========================================================================

NEG_ZONE = (0x800C87EC, 0x800CEE30)
NEG_SKIP = [(0x800C87EC, 0x800C882C), (0x800CB330, 0x800CB459)]   # btlui, btlcmd
NEG_SPILL = [(0x800D9294, 0x800D92F4)]   # the banner pool's last 96 bytes: text
                                        # storage inside BTLP, past 0x800C87EC so
                                        # the packing front still recognises it.
                                        # ban_build's pool stops here; the nine
                                        # names that lived there now spill.
NEG_OUT = os.path.join(ROOT, 'build', 'btlneg.asm')
NEG_BUF = EVT_BUF                           # the same unpack buffer (one constant)
NEG_EXTRA = [0x800C92B0, 0x800C9488, 0x800C94D0, 0x800C9968, 0x800CD518,
             0x800CB55C, 0x800C97B8]   # referenced strings the sequential scan swallows
# The sequencer reads these pointer-table ranges directly, without entering
# BtlTextOpen's unpacker (gift-card and parting-reward scripts respectively).
# Classify strings by their actual table references, not their scan order.
NEG_SEQ_POINTER_RANGES = ((0x800CD544, 0x800CD550), (0x800CD594, 0x800CD5B4))
NEG_PACK_IDX = (set(range(0, 34)) | set(range(35, 79))
                | set(range(168, 195)) | set(range(196, 300)))


def neg_seq_indices(strings, refs):
    return {i for i, (address, _) in enumerate(strings)
            if any(kind == 'word' and any(lo <= where < hi for lo, hi in NEG_SEQ_POINTER_RANGES)
                   for kind, where in refs.get(address, ()))}
NEG_STUB = """
;; unpacker front for negotiation strings (jumped to from btl_unpack when the string is below the story-battle zone):
;; a string of the negotiation zone starting with the marker byte 0 is byte-pair packed with the table at PAIRS
.org 0x800ABD50
.area 0x800ABDB0 - 0x800ABD50
btl_neg:
    la      t0, 0x800C87EC
    sltu    t1, a0, t0
    beqz    t1, @@in
    nop
    j       btl_unpack_store
    nop
@@in:
    lbu     t1, 0(a0)
    nop
    beqz    t1, @@pk
    nop
    j       btl_unpack_store
    nop
@@pk:
    la      t0, PAIRS
    sw      t0, 32(sp)
    j       btl_unpack_decode           ; negotiation bytes need not be halfword aligned
    addiu   a0, a0, 1
.endarea
"""


def neg_width(t):
    # ONE pricing (vwf_wrap.text_width): an insert token carries the name
    # or value the game fills it with, and the width table that prices it
    # is read from the decomp there - not retyped per family here.
    return vwf_wrap.text_width(t)


def neg_build(d, rows_by_pos, body):
    rf = _zone_refs(d, NEG_ZONE)
    strings = []
    p = NEG_ZONE[0]
    while p < NEG_ZONE[1]:
        if d[p - B] == 0:
            p += 1
            continue
        q = d.index(END, p - B) + 2 + B
        if not any(a <= p < b for a, b in NEG_SKIP) and p in rf:
            strings.append((p, q))
        p = q
    for a in NEG_EXTRA:
        strings.append((a, d.index(END, a - B) + 2 + B))
    new = {}
    for i, (a, q) in enumerate(strings):
        r = rows_by_pos.get(hex(a - B))
        t = laid((r['en'] if r else '').strip())
        if not t:
            continue
        orig = bytes(d[a - B:q - B])
        try:
            b = etext.encode(t, end=END)
        except ValueError:
            toolbelt.fail(f'neg {i} {t!r}: not encodable in the text charset')
        # a code difference is not a rendering problem - the Japanese
        # carries pauses and params the English does not need. Only what
        # the engine cannot SHOW is a problem (the buffer check below).
        if b.count(END) > 1:
            # an interior terminator ENDS the string: the engine stops there and
            # the rest of the row never draws, so it is not a rendering choice
            # but a composition that holds more than one message. The Japanese
            # ships and the row is reported (port_btlneg refuses it too).
            print(f'btlp neg {i}: {t!r} carries more than one message - '
                  f'Japanese ships')
            continue
        if codes(b, (0xF6, 0x05)) != codes(orig, (0xF6, 0x05)):
            pass
        if any(neg_width(ln) > vwf_wrap.BOX_WIDTH + 1
               for ln in re.split(r'<FFF6>|<FFFB><FFF7>', t)):
            toolbelt.fail(f'neg {i} {t!r}: over-wide, the box would wrap it '
                          f'mid-word (never shipped as-is)')
        new[i] = b
    seq = neg_seq_indices(strings, rf)
    packed_indices = NEG_PACK_IDX - seq
    for i, b in new.items():
        if i in packed_indices and len(b) > NEG_BUF:
            toolbelt.fail(f'neg {i}: exceeds the fixed unpack buffer, cannot build as-is')
        if i in packed_indices and len(b) > _equ('BTL_SECOND_BUF_SIZE'):
            toolbelt.fail(f'neg {i}: exceeds the second-window unpack buffer')
    if not new:
        return 0
    packed, pairs = bpe.pack({i: b for i, b in new.items() if i in packed_indices})
    for i in packed:
        new[i] = bytes((0,)) + packed[i]
    pair_blob = bytes(x for pr in pairs for x in pr)
    free = sorted(strings[i] for i in new)
    merged = []
    for a, q in free:
        if merged and not any(d[merged[-1][1] - B:a - B]):
            merged[-1][1] = q
        else:
            merged.append([a, q])
    place = {}
    shared = {}
    spill = [list(z) for z in NEG_SPILL]
    spilled = set()
    code = {i for i in new if any(k == 'addiu' for k, _ in rf.get(strings[i][0], []))}

    def put(zones, b):
        for z in zones:
            if z[1] - z[0] >= len(b):
                p = z[0]
                z[0] += len(b)
                return p
        return None

    if struct.unpack_from('<II', d, 0x8007D654 - B) != (0x3c01800f, 0xac30bb0c):
        toolbelt.fail('neg: second-window read-pointer writer changed')

    if features.on('SF_VWF'):
        import name_tails
        import items
        name_tails.build_battle_data()
        for index in range(toolbelt.asm_equ('BTLP_ITEM_ROWS')):
            body.append(f'.org BTLP_ITEM_DESC + {index} * 12 + 4\n'
                        f'.word BTLP_ITEM_FULL_ADDR + {index} * BTLP_ITEM_FULL_STRIDE\n'
                        '.byte 20\n'
                        f'.org BTLP_ITEM_DESC + BTLP_ITEM_ROWS * 12 + {index} * 12\n'
                        f'.halfword {(index & 1) * 128 - 20}')
        # Only messages using BtlTextOpen may use its unpacking front.
        for at, expected in (
            (0x8007a86c, (0x90a30000, 0x340200ff)),
            (0x800aadd8, (0x3c07800f, 0x94e77eb8, 0x00021140, 0x3c06800f)),
            (0x800aae5c, (0x80230000, 0x00000000, 0xa0c30009)),
            (0x800df7ac, (0x800f7dbc, 0x000c200a)),
            (0x800ad014, (0x96220000, 0x00000000, 0x304201ff)),
            (0x800ad49c, (0x3c01800d, 0x24212ad0, 0x002a0821)),
            (0x800751c0, (0x3c01800f, 0x2421b4cc)),
            (0x800751f8, (0x340200ff, 0x3c01800f, 0x2421b4cc, 0x00250821)),
            (0x8007520c, (0x3c02800f, 0x2442b4cc)),
            (0x800ad8a4, (0x82030049, 0x3c048010)),
            (0x800dea54, (0x800f6fb4, 0x000c2012)),
        ):
            if struct.unpack_from(f'<{len(expected)}I', d, at - B) != expected:
                toolbelt.fail(f'battle full names: retail hook changed at {at:#x}')
        with open(os.path.join(ROOT, 'build', 'sf_width.bin'), 'rb') as source:
            widths = source.read()
        with open(os.path.join(ROOT, 'build', 'btl_text_bits.bin'), 'rb') as source:
            text_bits = source.read()
        bank = bytearray()
        for ident, text in name_tails.demon_rows():
            glyphs = items.encode(text)
            if len(glyphs) > _equ('DEMON_NAME_MAXLEN'):
                toolbelt.fail(f'CONTACT demon {ident}: name exceeds scratch')
            if len(glyphs) + 7 + 1 > 24:
                toolbelt.fail(f'ANALYZE demon {ident}: name exceeds row storage')
            pen = right = 0
            for glyph in glyphs:
                metric = widths[glyph]
                if not metric & 15:
                    toolbelt.fail(f'CONTACT demon {ident}: glyph lacks metrics')
                if not text_bits[glyph >> 3] & (1 << (glyph & 7)):
                    toolbelt.fail(f'ANALYZE demon {ident}: glyph is not a text cell')
                right = max(right, pen - (metric >> 4) + 8)
                pen += metric & 15
            if right > (20 - 7) * 8:
                toolbelt.fail(f'CONTACT demon {ident}: name overlaps CARD')
            if right + 7 * 8 > 168:
                toolbelt.fail(f'ANALYZE demon {ident}: name overlaps status')
            if len(glyphs) > 10:
                bank.extend(bytes([ident]) + glyphs[10:] + b'\xff')
        bank.append(0)
        # Reserve from the same reclaimed negotiation strings as the text;
        # alignment is required for the executable part, not for the bank.
        code_at = None
        for z in merged:
            at = (z[0] + 3) & ~3
            if at + 108 <= z[1]:
                code_at = at
                z[0] = at + 108
                break
        bank_at = put(merged, bank)
        analyze_at = None
        for z in merged:
            at = (z[0] + 3) & ~3
            if at + 56 <= z[1]:
                analyze_at = at
                z[0] = at + 56
                break
        if code_at is None or bank_at is None or analyze_at is None:
            toolbelt.fail('CONTACT: no room for full demon names')
        full_code_at = None
        for z in merged:
            at = (z[0] + 3) & ~3
            if at + 640 <= z[1]:
                full_code_at = at
                z[0] = at + 640
                break
        if full_code_at is None:
            toolbelt.fail('battle names: no bounded home for complete-name helpers')

    pairs_at = put(merged, pair_blob) if pair_blob else 0
    if pair_blob and pairs_at is None:
        toolbelt.fail('neg: no room for the pair table')
    for i in sorted(new, key=lambda i: (i not in code, -len(new[i]))):
        b = new[i]
        if b in shared:
            place[i] = shared[b]
            continue
        p = put(merged, b)
        if p is None and i not in code:
            p = put(spill, b)
            spilled.add(b)
        if p is None:
            toolbelt.fail(f'neg: out of space at {i} ({len(b)} bytes); '
                          f'free {[(hex(a), e - a) for a, e in merged + spill]}')
        place[i] = shared[b] = p
    for i in new:
        a, q = strings[i]
        body.append(f'.org {a:#x}\n    .fill {q - a}, 0')
    for a, q in NEG_SPILL:
        body.append(f'.org {a:#x}\n    .fill {q - a}, 0')
    if features.on('SF_VWF'):
        body.append(f'.org {bank_at:#x}\n    .byte ' + ', '.join(f'0x{x:02X}' for x in bank))
        body.append(f'.definelabel OFFER_NAME_CODE, {code_at:#x}\n'
                    f'.definelabel OFFER_NAME_BANK, {bank_at:#x}\n'
                    f'.definelabel ANALYZE_NAME_CODE, {analyze_at:#x}\n'
                    '.include "btlp/offer_name.asm"')
        body.append(f'.definelabel BTL_FULL_NAME_CODE, {full_code_at:#x}\n'
                    f'.org {full_code_at + 320:#x}\n'
                    '.area 320\n'
                    '.include "../../build/item_name_copy_btlp.asm"\n'
                    '.endarea\n'
                    '.include "btlp/full_names.asm"\n'
                    '.include "../../build/name_data_btlp.asm"')
    for b, p in shared.items():
        body.append(f'.org {p:#x}\n    .byte ' + ', '.join(f'0x{x:02X}' for x in b))
    if pair_blob:
        body.append(f'.org {pairs_at:#x}\n    .byte ' + ', '.join(f'0x{x:02X}' for x in pair_blob))
    body.append(NEG_STUB.replace('PAIRS', f'{pairs_at:#x}').strip())
    for i in new:
        for kind, w in rf.get(strings[i][0], []):
            if kind == 'word':
                body.append(f'.org {w:#x}\n    .word {place[i]:#x}')
            else:
                body.append(f'.org {w:#x}\n    .halfword {place[i] & 0xFFFF:#x}')
    print(f'btlp neg: {len(new)}/{len(strings)} translated, '
          f'{sum(len(b) for b in shared)} bytes placed')
    return len(new)


# ===========================================================================
# family: banner (battle banner names)
# ===========================================================================

BAN_COUNT = 347
BAN_TABLE = 0x800D92F4
BAN_POOL = (0x800D835C, 0x800D92F4)
# Placement stops before the last 96 bytes: NEG_SPILL needs text storage above
# the negotiation zone (its packing front keys on that range), and this tail is
# the pool's own proven string space - only the pointer table addresses it, so
# moving those nine names into the banner spill costs nothing.
BAN_POOL_END = 0x800D9294
# 0x8002C248..0x8002C2F0 is reserved for the skill menu's future
# seven 24-byte slots. The same source-derived banner packer uses its other
# already-owned fragments instead; no banner text is shortened or dropped.
BAN_SPILL = [(0x80026A10, 0x80026A54), (0x80018B50, 0x80018B88),
             (0x8002C374, 0x8002C3E0)]
BAN_OUT_BTLP = os.path.join(ROOT, 'build', 'banner_btlp.asm')
BAN_OUT_SLPS = os.path.join(ROOT, 'build', 'banner_slps.asm')


def ban_decode(d, p):
    out, i = [], p - B
    while d[i] != 0xFF:
        c = d[i]
        if 0x80 <= c <= 0x87:
            g = ((c & 7) << 8) | d[i + 1]
            i += 2
        else:
            g = c
            i += 1
        out.append(etext.glyph.get(g, '<G%03X>' % g))
    return ''.join(out)


def ban_records(d):
    out = []
    for k in range(BAN_COUNT):
        p = struct.unpack_from('<I', d, BAN_TABLE + 4 * k - B)[0]
        if not BAN_POOL[0] <= p < BAN_POOL[1]:
            toolbelt.fail(f'banner record {k}: pointer {p:#x} outside the pool')
        out.append((k, p, ban_decode(d, p)))
    return out


def ban_encode(t):
    """Action banners use BtlOpenMessage and the battle dialogue VWF.

    Encode each source character as dialogue ASCII, not the unrelated 8px
    small-font charset. Controls are not names and are never synthesized here.
    """
    return bytes(etext.vwf_byte(c) for c in t)


def ban_build(d, rows_by_pos, body):
    want = {}
    n = 0
    for k, p, _ja in ban_records(d):
        r = rows_by_pos.get(hex(p - B))
        t = (r['en'] if r else '').strip()
        if t:
            want[k] = ban_encode(t) + END
            n += 1
        else:                                    # untranslated: original bytes
            i = p - B
            j = d.index(END, i)
            want[k] = bytes(d[i:j + 2])
    placed = {}
    zones = [[BAN_POOL[0], BAN_POOL_END]] + [list(z) for z in BAN_SPILL]
    chunks = {i: [] for i in range(len(zones))}
    # Stable tie-breaking keeps standalone builds reproducible independently
    # of Python's hash seed; the suffix-sharing rule is otherwise unchanged.
    for s in sorted(set(want.values()), key=lambda value: (-len(value), value)):
        host = next((h for h in placed if h.endswith(s)), None)
        if host is not None:
            placed[s] = placed[host] + len(host) - len(s)
            continue
        for zi, z in enumerate(zones):
            if z[1] - z[0] >= len(s):
                placed[s] = z[0]
                chunks[zi].append((z[0], s))
                z[0] += len(s)
                break
        else:
            toolbelt.fail(f'banner: out of space ({len(s)} bytes for {s.hex()})')
    lines = [f'.org {BAN_POOL[0]:#x}\n.area {BAN_POOL_END - BAN_POOL[0]:#x}, 0']
    for a, s in chunks[0]:
        lines.append('    .byte ' + ', '.join(f'0x{c:02X}' for c in s))
    lines.append('.endarea')
    lines.append(f'.org {BAN_TABLE:#x}')
    for k in range(BAN_COUNT):
        lines.append(f'    .word {placed[want[k]]:#x}')
    toolbelt.write_asm(BAN_OUT_BTLP, 'btlp', '\n'.join(lines) + '\n')
    spilled = []
    for zi in range(1, len(zones)):
        for a, s in chunks[zi]:
            spilled.append(f'.org {a:#x}\n    .byte ' + ', '.join(f'0x{c:02X}' for c in s))
    toolbelt.write_asm(BAN_OUT_SLPS, 'btlp',
                       ';; battle banner names that did not fit BTLP\n'
                       + ('\n'.join(spilled) + '\n' if spilled else ''))
    print(f'btlp banner: {n}/{BAN_COUNT} translated, '
          f'pool {zones[0][0] - BAN_POOL[0]}/{BAN_POOL_END - BAN_POOL[0]} bytes')
    return n


