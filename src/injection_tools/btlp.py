def verify_highlight_ownership(stock, built):
    """Text relocation must never patch the separate retail HUD highlight."""
    lo, hi = 0x80076878 - B, 0x80076b70 - B
    if len(stock) < hi or len(built) < hi or stock[lo:hi] != built[lo:hi]:
        toolbelt.fail('btlp verify: retail battle highlight code was overwritten')


def verify():
    """Independently reassemble and read back the battle unpacker and its data."""
    root = Path(ROOT)
    built = (root / 'build/BTLP.BIN').read_bytes()
    exe = (root / 'build/SLPS_005.00').read_bytes()
    exe_base, exe_size = struct.unpack_from('<II', exe, 0x18)
    symbols = {}
    for line in (root / 'build/persona.sym').read_text().splitlines():
        m = re.match(r'^([0-9a-fA-F]{8})\s+(\S+)', line)
        if m:
            symbols[m[2]] = int(m[1], 16)
    hook, code_end, pairs, pairs_end = (symbols[n] for n in
        ('btl_second_unpack', 'btl_unpack_code_end', 'btlevt_pairs', 'btlevt_pairs_end'))
    if not (hook == EVT_UNPACK < code_end == pairs <= pairs_end <= EVT_ZONE[1]):
        toolbelt.fail('btlp verify: unpacker or pair table is outside its reserved tail')
    stock = data()
    verify_highlight_ownership(stock, built)
    import battle_board_text
    expected_drafts = board_drafts(stock, toolbelt.merged_rows(REL))
    draft_path = root / 'build/btl_board_drafts.tsv'
    try:
        battle_board_text.verify_retail_bytes(stock, built)
        battle_board_text.verify_draft_report(draft_path.read_text(encoding='utf-8').splitlines(), expected_drafts)
    except (OSError, ValueError) as error:
        toolbelt.fail(f'btlp verify: {error}')
    plan = evt_plan(stock, {r['pos']: r for r in toolbelt.merged_rows(REL)})
    expected_pairs = bytes(x for pair in plan['pairs'] for x in pair)
    if len(plan['packed']) != len(plan['msgs']):
        toolbelt.fail('btlp verify: not every original message has an owned packed form')
    if built[pairs-B:pairs_end-B] != expected_pairs:
        toolbelt.fail('btlp verify: assembled story pair table differs from the generated pairs')

    # Armips permits later .org writes to overwrite code silently. Assemble
    # this exact source alone against retail BTLP, using the final symbols,
    # and compare the complete hook and code, not just a prologue.
    armips = next((str(p) for p in (root / 'external_tools/armips/armips.exe',
                                    root / 'external_tools/armips/armips') if p.exists()), None) or shutil.which('armips')
    if not armips:
        toolbelt.fail('btlp verify: armips is required for independent readback')
    names = ('BTLEVT_ZONE_START', 'BTLEVT_ZONE_END', 'BTLEVT_UNPACK_ADDR',
             'BTLEVT_BUF_ADDR', 'BTLEVT_MARK', 'BTLEVT_SPILL_ADDR', 'BTLEVT_SPILL_END',
             'BTLEVT_SPILL2_ADDR', 'BTLEVT_SPILL2_END', 'BTLEVT_SPILL3_ADDR',
             'BTLEVT_SPILL3_END', 'BTLEVT_SPILL4_ADDR', 'BTLEVT_SPILL4_END',
             'BTL_SECOND_BUF_ADDR')
    defs = {name: _equ(name) for name in names}
    defs['btl_neg'] = symbols['btl_neg']
    asm_root = root / 'src/asm'
    with tempfile.TemporaryDirectory(prefix='btlp-unpacker-') as tmp:
        source = Path(tmp) / 'verify.asm'
        dest = Path(tmp) / 'BTLP.BIN'
        source.write_text('.psx\n' + ''.join(f'.definelabel {k}, 0x{v:X}\n' for k, v in defs.items())
            + f'.open "{root / "data/psx/BTLP.BIN"}", "{dest}", 0x{B:X}\n'
            + f'.include "{asm_root / "btlp/btlevt_unpack.asm"}"\n.close\n')
        result = subprocess.run([armips, str(source)], cwd=asm_root, capture_output=True, text=True)
        if result.returncode:
            toolbelt.fail('btlp verify: isolated assembler failed: ' + result.stdout + result.stderr)
        independent = dest.read_bytes()
    for lo, hi in ((0x8007D0B4, 0x8007D0BC), (0x8007D654, 0x8007D65C), (hook, pairs_end)):
        if built[lo-B:hi-B] != independent[lo-B:hi-B]:
            toolbelt.fail('btlp verify: assembled unpacker hook/code differs from independent assembly')

    def image_bytes(address, size):
        if B <= address and address + size <= B + len(built):
            return built[address-B:address-B+size]
        if exe_base <= address and address + size <= exe_base + exe_size:
            offset = 0x800 + address - exe_base
            return exe[offset:offset+size]
        toolbelt.fail(f'btlp verify: packed address {address:#x} is outside its loaded image')

    if features.on('SF_VWF'):
        import items
        import name_tails
        import slps
        bank = bytearray()
        tails = bytearray((slps.IT_COUNT + 7) // 8)
        english = bytearray((slps.IT_COUNT + 8) // 8)
        for ident, text in name_tails.item_rows():
            english[ident // 8] |= 1 << (ident % 8)
            _, tail = name_tails.split(text, items.FIELD, name_tails.ITEM_MAXLEN, f'item {ident}')
            if tail:
                tails[(ident - 1) // 8] |= 1 << ((ident - 1) % 8)
                bank.extend(bytes([len(tail)]) + tail)
        compact = bytearray(215)
        for char in "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789 .'-/:":
            compact[items.glyph(char)] = etext.encode(char, end=None)[0]
        expected_data = bytes(bank + tails + compact + english)
        start = _equ('BTLP_NAME_DATA_ADDR')
        end = symbols['btl_name_data_end']
        if (symbols['item_tail_bank_btlp'] != start or end != start + len(expected_data)
                or end > _equ('BTLP_NAME_DATA_END')
                or image_bytes(start, len(expected_data)) != expected_data):
            toolbelt.fail('btlp verify: full-name data differs or reaches sound work memory')
        def jump(address, label):
            expected = 0x08000000 | ((symbols[label] >> 2) & 0x03ffffff)
            if struct.unpack('<I', image_bytes(address, 4))[0] != expected:
                toolbelt.fail(f'btlp verify: {label} hook changed at {address:#x}')
        jump(0x8007A86C, 'btl_name_copy')
        jump(0x800AD49C, 'btl_list_spell_terminate')
        result_ptr, result_count = struct.unpack('<IB', image_bytes(0x800DF7AC, 5))
        if (result_ptr, result_count) != (_equ('PERSONA_HDR_BUF'), 20):
            toolbelt.fail('btlp verify: victory item descriptor changed')

    for i, (start, _end) in enumerate(plan['msgs']):
        address, packed = plan['place'][i], plan['packed'][i]
        if image_bytes(address, len(packed)) != packed:
            toolbelt.fail(f'btlp verify: packed message {i} was overwritten at {address:#x}')
        for kind, where in plan['rf'].get(start, []):
            got = image_bytes(where, 4 if kind == 'word' else 2)
            expected = (struct.pack('<I', address) if kind == 'word'
                        else struct.pack('<H', address & 0xFFFF))
            if got != expected:
                toolbelt.fail(f'btlp verify: message {i} reference at {where:#x} was overwritten')
    for address, packed in plan['spill'].items():
        if image_bytes(address, len(packed)) != packed:
            toolbelt.fail(f'btlp verify: resident packed text was overwritten at {address:#x}')
    rows = {r['pos']: r for r in toolbelt.merged_rows(REL)}
    for index, original, _ja in ban_records(stock):
        row = rows.get(hex(original - B), {})
        text = (row.get('en') or '').strip()
        if text:
            expected = ban_encode(text) + END
        else:
            start = original - B
            end = stock.index(END, start) + len(END)
            expected = stock[start:end]
        pointer = struct.unpack('<I', image_bytes(BAN_TABLE + index * 4, 4))[0]
        if image_bytes(pointer, len(expected)) != expected:
            toolbelt.fail(f'btlp verify: action banner {index} at {pointer:#x} differs')
    print(f'btlp verify: {len(plan["msgs"])} messages, {len(plan["pairs"])} pairs, '
          f'{BAN_COUNT} action banners; unpacker {hook:#x}..{pairs_end:#x}, '
          f'checked code, text and references')


