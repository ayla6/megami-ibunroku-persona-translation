def neg_is_data(d, a, e):
    """Is this referenced run of the negotiation zone DATA, not a string?

    neg_strings takes every referenced address up to the next end mark, and
    code also references the zone's tables (lui/addiu), so pointer tables and
    record blobs arrive as 'strings' ('ＫブしＳブし…'). Two facts of the
    encoding tell them apart: a table of 32-bit RAM addresses opens with two
    aligned words in 0x80010000..0x80200000, and text never holds a byte
    E7..FE outside a two-byte glyph (80..87 xx) or a control (FF xx) - the
    lead bytes are 00..7F glyphs, 80..87 two-byte glyphs, 88..E6 English."""
    raw = d[a - B:e - B - 2]
    if len(raw) >= 8:
        w0, w1 = struct.unpack_from('<II', raw, 0)
        if all(0x80010000 <= w < 0x80200000 and w % 4 == 0 for w in (w0, w1)):
            return True
    i = 0
    while i < len(raw):
        b = raw[i]
        if b == 0xFF or 0x80 <= b <= 0x87:
            i += 2
            continue
        if 0xE7 <= b <= 0xFE:
            return True
        i += 1
    return _not_language(dec(d, a, e))


def _not_language(text):
    """Does a decodable run still refuse to be a message?

    The zone also holds debug material: name-entry keyboard pages, padded
    kana fields, glyph tables and page-scroll tests. Their bytes pass the
    encoding checks above, but a displayed message cannot look like them:

    - an unknown glyph or control ('<G...>') means the run is a table of
      raw cell codes, not text;
    - a padded field of single kana has no sentence punctuation and many
      ideographic spaces (the name-entry pages and the kana-test fields);
    - a page-scroll test pages ellipsis filler with at most one real glyph
      per page; no sentence is built that way.
    """
    if '<G' in text:
        return True
    shown = re.sub(r'<[^>]*>', '', text)
    if (len(shown) >= 20 and shown.count('\u3000') >= 4
            and not any(c in shown for c in '。！？、，．')):
        return True
    pages = text.split('<FFFB><FFF7>')
    if len(pages) >= 2:
        for page in pages:
            v = re.sub(r'<[^>]*>', '', page)
            if not v or '…' not in v or len(v.replace('…', '')) > 1:
                return False
        return True
    return False


def families(d):
    """[(pos, family)] every row slot in file order. A negotiation-zone run
    that is data (neg_is_data) is not a row: nothing displays it."""
    out = []
    for a, _e in evt_messages(d):
        out.append((a - B, 'evt'))
    for a, e in neg_strings(d):
        if neg_is_data(d, a, e):
            continue
        out.append((a - B, 'neg'))
    for a, _e in msg_messages(d):
        out.append((a - B, 'msg'))
    for _k, p, _ja in ban_records(d):
        out.append((p - B, 'banner'))
    import battle_board_text
    out.extend((off, 'board') for off, _ja in battle_board_text.scan(d))
    return out


def neg_strings(d):
    rf = _zone_refs(d, NEG_ZONE)
    out = []
    p = NEG_ZONE[0]
    while p < NEG_ZONE[1]:
        if d[p - B] == 0:
            p += 1
            continue
        q = d.index(END, p - B) + 2 + B
        if not any(a <= p < b for a, b in NEG_SKIP) and p in rf:
            out.append((p, q))
        p = q
    for a in NEG_EXTRA:
        out.append((a, d.index(END, a - B) + 2 + B))
    return out


def msg_messages(d):
    out = []
    p = MSG_ZONE[0]
    while p < MSG_ZONE[1]:
        if d[p - B] == 0:
            p += 1
            continue
        e = d.index(END, p - B) + 2 + B
        out.append((p, e))
        p = e
    return out


