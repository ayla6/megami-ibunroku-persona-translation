# The PSP-wording reader is toolbelt's, the box layout and the family
# spelling are port_derive's, the field rules are port_caps': promote uses
# those, never a copy of them.


def banner_wording():
    """{banner record: (PSP-US name, locator)} from the boot name tables.

    The banner list is positional: BANNER 1-242 = skills[k-1], 243-346 =
    items[k-243] (boot_tables.gen_banner's verified mapping). The wording
    is the table's NAME FIELD, read by the table reader - the EBOOT box
    extract is not usable here: its box scanner starts on the previous
    record's trailer, which is where the ',Garula' / '<FF0C>Doroid'
    prefixes come from (extraction artefacts, never wording). The locator
    is the exact byte offset of that name field.
    """
    import boot_tables as bt
    out = {}
    for fam, lo, hi, first in (('skills', 1, 242, 1), ('items', 243, 346, 243)):
        base, stride, count, off, length = bt.TABLES[fam]
        names = bt.table_names(base, stride, count, off, length) or []
        for k in range(lo, hi + 1):
            i = k - first
            if not 0 <= i < len(names):
                continue
            out[k] = (names[i], f'EBOOT:{base + stride * i + off * 2:#x}')
    return out


def _family_index(d):
    """{file offset: (family, index, start, end, info)} for every dialogue
    row, using the same scans the builders use."""
    out = {}
    rf = evt_refs(d)
    for i, (a, e) in enumerate(evt_messages(d)):
        out[a - B] = ('evt', i, a, e, bool(rf.get(a)))
    rf = _zone_refs(d, MSG_ZONE)
    for i, (a, e) in enumerate(msg_messages(d)):
        out[a - B] = ('msg', i, a, e, a in rf)
    for i, (a, e) in enumerate(neg_strings(d)):
        out[a - B] = ('neg', i, a, e, i in NEG_PACK_IDX)
    return out


def _accept(fam, t, a, e, info):
    """(encoded bytes, '') when the family builder can show this wording,
    else (None, reason). The rules are the builders' own: a row nothing
    re-points must fit its slot; a relocated row is limited by the box
    layout (and the pack buffer for a packed negotiation row). Capacity of
    a shared zone/spill is the build's own check - a draft is never
    shortened for it."""
    try:
        b = etext.encode(t, end=END)
    except ValueError as ex:
        return None, str(ex)
    if fam == 'evt':
        if len(b) > EVT_BUF:
            return None, toolbelt.note_over(len(b), EVT_BUF, 'B')
        for page in re.split(r'<FFFB><FFF7>|<FF04>', t):
            lines = page.split('<FFF6>')
            if len(lines) > 4:
                return None, toolbelt.note_over(len(lines), 4, 'lines')
            for ln in lines:
                w = vwf_wrap.text_width(ln)
                if w > 239:
                    return None, toolbelt.note_over(w, 239, 'px')
        if not info and len(b) > e - a and e - a < EVT_MARK_LEN:
            # A slot only has to hold 'FF 00 hi lo' (evt_plan): the size that
            # can refuse wording is the one too small for even that pointer.
            # Anything bigger is the build's own placement question - this
            # pre-check may leave a draft, never promise a row that will not
            # ship, and the raw bytes here are still an upper bound on the
            # packed size.
            return None, toolbelt.note_over(len(b), e - a, 'B')
    elif fam == 'msg':
        w = vwf_wrap.text_width(t)
        if w > 239:
            return None, toolbelt.note_over(w, 239, 'px')
        if not info and len(b) > e - a:
            return None, toolbelt.note_over(len(b), e - a, 'B')
    elif fam == 'neg':
        if any(neg_width(ln) > vwf_wrap.BOX_WIDTH + 1
               for ln in re.split(r'<FFF6>|<FFFB><FFF7>', t)):
            return None, 'over-wide (the box would wrap mid-word)'
        if info and len(b) > NEG_BUF:
            return None, toolbelt.note_over(len(b), NEG_BUF, 'B')
    return b, ''


def promote():
    """Fill the machine-draftable BTLP rows from the PSP-US data.

    Banners have their own source-derived family porter. Dialogue: a row whose
    `psp` names a PSP unit gets that unit's wording, laid out by the shared box
    layout and accepted only where this file's builder can show it. A
    draft the destination cannot hold is refreshed through route_over (the
    only over-limit writer), never shortened; a row with no `psp` source
    is a finding, not a wording, and stays as it is.
    """
    d = data()
    gen = {r['pos'] for r in toolbelt.read_generated(REL)}
    man = toolbelt.read_manual(REL)
    idx = _family_index(d)
    new = []
    counts = collections.Counter()
    rejected = []

    for r in man:
        pos = r['pos']
        if (r.get('en') or '').strip() or pos in gen:
            continue
        psp = (r.get('psp') or '').strip()
        if not psp:
            continue
        try:
            off = int(pos, 16)
        except ValueError:
            continue
        hit = idx.get(off)
        if hit is None:
            continue
        fam, _i, a, e, info = hit
        ja = dec(d, a, e)
        w = toolbelt.psp_wording(psp).strip()
        if not etext.has_text(w):
            continue
        import match_jp
        raw = port_derive.fit_codes(
            w, ja, strict=port_caps.is_fixed_field(REL, pos))
        t = laid(port_derive.lay_out(raw, REL, ja))
        if not etext.has_text(t):
            draft = raw
            reason = (port_derive.unlayable_note(raw)
                      or 'cannot be laid out in the box')
        else:
            draft = t
            _b, reason = _accept(fam, t, a, e, info)
        if reason:
            rejected.append((pos, psp, draft, reason))
            counts[f'{fam} rejected'] += 1
            continue
        new.append({'pos': pos, 'psp': psp, 'en': t})
        counts[fam] += 1

    n = toolbelt.upsert_generated(REL, new)
    for pos, psp, draft, reason in rejected:
        toolbelt.route_over(REL, pos, psp, draft, reason)
    print(f'btlp promote: {n} rows written, '
          + ', '.join(f'{k} {v}' for k, v in sorted(counts.items())
                      if not k.endswith('rejected'))
          + (f'; rejected {sum(v for k, v in counts.items() if k.endswith("rejected"))}'
             if any(k.endswith('rejected') for k in counts) else ''))
    return n


