"""The dungeon run action's name, and the controller page's action-name table.

  python src/injection_tools/runtext.py     write build/runtext_dng.asm

The run action is not a settings row of its own: it is one more action in the
game's controller page, so its name is drawn by that page's own name table.
PadDrawLayout reads the 19-pointer retail action-name table, which sits right
in front of the layout table - there is no room for a 20th pointer between
them - so the whole table is copied into the DNG image extension with the new
pointer appended, and PadDrawLayout's table base load is repointed at the copy
(qol/run_dng.asm).

The name is the `runtext` / `name` row of translation/manual/terms.tsv, a
small-font tile row (1 byte per cell, same encoding as tools/items.py: A-Z are
the full-width glyph codes, space = 0). The other 19 pointers are read from
the retail image, so every name the translation writes in place keeps
pointing at its own string; nothing here spells an action name.
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import items      # noqa: E402
import strlib     # noqa: E402
import toolbelt   # noqa: E402

ROOT = toolbelt.ROOT
NL = '\n'
REL = 'DNG'


def enc(text):
    """Small-font row bytes: the same glyph map the config labels use."""
    return bytes(items.glyph(c) for c in text)


def main():
    terms = strlib.glossary('runtext')
    if 'name' not in terms:
        toolbelt.fail('runtext: translation/manual/terms.tsv has no runtext/name row')
    name = terms['name']

    name_at = toolbelt.asm_equ('DNG_RUN_NAME')
    name_room = toolbelt.asm_equ('DNG_RUN_NAME_ROOM')
    table_at = toolbelt.asm_equ('DNG_RUN_PAD_NAMES')
    retail_at = toolbelt.asm_equ('DNG_PAD_NAMES')
    count = toolbelt.asm_equ('DNG_PAD_NAME_COUNT')
    run_index = toolbelt.asm_equ('DNG_PAD_RUN_INDEX')
    code_at = toolbelt.asm_equ('DNG_RUN_ADDR')
    # DNG_RUN_LIMIT in addresses.inc, which is this same end of the image.
    limit = toolbelt.asm_equ('DNG_PDATA_EXT_LIMIT')

    if run_index != count:
        toolbelt.fail(f'runtext: the run action is {run_index}, but only {count} '
                      'retail action names exist (the new pointer must follow them)')
    if table_at < name_at + name_room:
        toolbelt.fail('runtext: the action-name table overlaps the run name row')
    if table_at + (count + 1) * 4 > code_at:
        toolbelt.fail('runtext: the action-name table runs into the walk hook')
    if table_at + (count + 1) * 4 > limit:
        toolbelt.fail('runtext: the action-name table runs past the loaded image extension')

    name_bytes = enc(name) + b'\xFF'
    if len(name_bytes) > name_room:
        toolbelt.fail(f'runtext: {name!r} is {len(name_bytes) - 1} cells, '
                      f'room {name_room - 1}')
    name_bytes += bytes(name_room - len(name_bytes))

    image = open(toolbelt.bin_path(REL), 'rb').read()
    off = toolbelt.va_file_offset(retail_at)
    if off + 4 * count > len(image):
        toolbelt.fail(f'runtext: the action-name table is not inside {REL}.BIN')
    pointers = list(struct.unpack_from(f'<{count}I', image, off))
    end = toolbelt.OVERLAY_SLOT + len(image)
    for index, pointer in enumerate(pointers):
        if not toolbelt.OVERLAY_SLOT <= pointer < end:
            toolbelt.fail(f'runtext: action name {index} points outside {REL}.BIN '
                          f'({pointer:#x})')

    body = [f';; generated by src/injection_tools/runtext.py - do not edit (DNG){NL}']
    body.append(f'; the run action name: "runtext name" from terms.tsv{NL}')
    body.append(f'.org {name_at:#x}{NL}    .byte '
                + ', '.join(f'0x{x:02X}' for x in name_bytes) + NL)
    body.append(f'; g_pad_action_names[{count}]: the retail pointers, then the run action{NL}')
    body.append(f'.org {table_at:#x}{NL}    .word '
                + ', '.join(f'0x{pointer:08X}' for pointer in pointers + [name_at]) + NL)
    body.append('.if . > DNG_RUN_LIMIT' + NL
                + '    .error "runtext: the name table overruns the loaded image extension"' + NL
                + '.endif' + NL)

    path = os.path.join(ROOT, 'build', 'runtext_dng.asm')
    toolbelt.ensure_parent(path)
    with open(path, 'w', newline=NL) as handle:
        handle.write(''.join(body))
    print(f'runtext: {name!r} + {count} retail names -> {os.path.relpath(path, ROOT)}')


if __name__ == '__main__':
    main()
