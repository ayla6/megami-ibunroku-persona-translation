"""Velvet Room fusion messages (ADV) + small-font -> VWF map for inserted names.

  python tools/fusionmsg.py      write build/fusionmsg_slps.asm, build/fusionmsg_adv.asm, build/vwf_small_map.asm

1) Igor's two messages after a fusion live in ADV.BIN at 0x800B8CF0 (accident: "おっと イレギュラーのようです") and
   0x800B8D08 ("このペルソナは… <arcana> <name>です … 以後よしなに…"). The second one is reached by offset: ADV
   0x8008A7A0 points v1 at the <FF13> parameter byte, a0 = v1 - 0xE is the message, and the arcana / Persona ids are
   stored into the <FF13> and <FF0C> parameter bytes at run time (0x8008A7BC, 0x8008A7C4). The English versions are
   placed in the free affinity records (slps_005.00/aff_free.asm) and these instructions are re-pointed.
2) <FF13>/<FF0C> insert small-font table strings (arcana, Persona / demon / item names) through the engine's
   name-insertion path; English there is small-font bytes (A = 0xA6, a..z = reused kana codes, tools/skills.py), which
   the dialogue VWF would read as its own ASCII bytes (0xB1 'L' became 'I'). vwf_glyph_map_small (aff_free.asm)
   translates them with vwf_small_map on that path only.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import etext   # noqa: E402
import skills  # noqa: E402
import strlib  # noqa: E402

ROOT = etext.ROOT
NL = chr(10)
MAP_LEN = 0xD0
MAP_PAGE_SIZE = 8

_FM = strlib.glossary('fusionmsg')
ACCIDENT = (_FM['accident'], bytes([0x08, 0x00]))
# (english before the arcana line, english after the name, wait param, english of the last line, wait param)
RESULT = (_FM['result_pre'], _FM['result_after'], bytes([0x10, 0x00]), _FM['result_last'], bytes([0x20, 0x00]))


def enc(t):
    return etext.encode(t)[:-2]                       # without the trailing FF01


def byte_lines(b):
    return '    .byte ' + ', '.join(f'0x{x:02X}' for x in b) + NL


def compact_map(table):
    """One-based page offsets; share exact suffix/prefix bytes losslessly."""
    source = [bytes(table[i:i + MAP_PAGE_SIZE])
              for i in range(0, len(table), MAP_PAGE_SIZE)]
    chunks = list(dict.fromkeys(page for page in source if any(page)))
    while len(chunks) > 1:
        candidates = []
        for i, left in enumerate(chunks):
            for j, right in enumerate(chunks):
                if i == j:
                    continue
                overlap = next((n for n in range(min(len(left), len(right)), 0, -1)
                                if left[-n:] == right[:n]), 0)
                candidates.append((overlap, -i, -j))
        overlap, i, j = max(candidates)
        i, j = -i, -j
        merged = chunks[i] + chunks[j][overlap:]
        chunks = [chunk for n, chunk in enumerate(chunks) if n not in (i, j)] + [merged]
    data = bytearray(chunks[0] if chunks else b'')
    pages = bytearray()
    for page in source:
        if any(page):
            offset = data.index(page)
            if offset >= 255:
                raise SystemExit('fusionmsg: compact map offsets exceed one byte')
            pages.append(offset + 1)
        else:
            pages.append(0)
    return pages, data


def main():
    out = [';; generated by tools/fusionmsg.py - do not edit' + NL]
    t, w = ACCIDENT
    out.append('fusion_msg_accident:' + NL + byte_lines(enc(t) + b'\xff\x05' + w + b'\xff\x01'))
    pre, after, w1, last, w2 = RESULT
    out.append('fusion_msg_result:' + NL + byte_lines(enc(pre) + b'\xff\x03\xff\x13'))
    out.append('fusion_msg_arc_param:' + NL + byte_lines(b'\xbb\xff\x03\xff\x0c'))
    out.append('fusion_msg_name_param:' + NL + byte_lines(b'\xbb' + enc(after) + b'\xff\x05' + w1 + b'\xff\x03'
                                                            + enc(last) + b'\xff\x05' + w2 + b'\xff\x01'))
    open(os.path.join(ROOT, 'build', 'fusionmsg_slps.asm'), 'w', newline=NL).write(''.join(out))

    adv = f''';; generated by tools/fusionmsg.py - do not edit (ADV section)
.org 0x8008A524
    lui     a0, hi(fusion_msg_accident)
    addiu   a0, a0, lo(fusion_msg_accident)
.org 0x8008A7A0
    lui     v1, hi(fusion_msg_arc_param)
    addiu   v1, v1, lo(fusion_msg_arc_param)
    addiu   a0, v1, fusion_msg_result - fusion_msg_arc_param
.org 0x8008A7C0
    lui     at, hi(fusion_msg_name_param)
    sb      v0, lo(fusion_msg_name_param)(at)
'''
    open(os.path.join(ROOT, 'build', 'fusionmsg_adv.asm'), 'w', newline=NL).write(adv)

    table = bytearray(MAP_LEN)
    for c in range(32, 127):
        ch = chr(c)
        if ch.isalnum() or ch in " .'/:-":
            g = skills.glyph(ch)
            assert g < MAP_LEN and not table[g], ch
            table[g] = c
    with open(os.path.join(ROOT, 'build', 'vwf_small_map.asm'), 'w', newline=NL) as o:
        pages, data = compact_map(table)
        o.write(';; generated by tools/fusionmsg.py: overlapping 8-byte pages' + NL)
        o.write('vwf_small_pages:' + NL + byte_lines(pages))
        o.write('vwf_small_map:' + NL)
        for i in range(0, len(data), 16):
            o.write(byte_lines(data[i:i + 16]))
    print(f'fusionmsg: 2 messages, small-font map {sum(1 for x in table if x)} codes')


if __name__ == '__main__':
    main()
