"""Feature gates - one switch per optional subsystem, shared by the build and the asm.

The build writes `build/features.inc`, and `main.asm` includes it before any
other include. Every gate is then one `.if` in the assembly, and this module is
the only thing that decides it:

    SF_VWF    the small-font VWF kit: the TileMapWriteRow recorder, the libgs
              sorter stubs/gate/replays, the FONT.BIN anchor, the per-overlay
              renderer and its data block.
    SF_LATIN  the latin cells of the small font page (a..z + the punctuation
              the page lacks, drawn over rare hiragana). NOT the kit: the
              retail renderer reads a byte as a kana, so these cells are what
              makes english printable at all. On with SF_VWF off = readable
              text through the retail renderer, which is a legitimate build
              (and the only way to tell the two subsystems apart in game).

A gate is ALL OR NOTHING. Off means none of the subsystem's bytes are in the
disc: the writer hook, the sorter stubs, the FONT.BIN atlas cells and the
overlay extension blocks are all skipped by the same flag, so "disabled" is a
clean retail build of that subsystem and can be compared byte for byte.

    python src/injection_tools/build.py                # every gate on (default)
    python src/injection_tools/build.py --no-sf-vwf    # the kit off, latin cells on
    python src/injection_tools/build.py --no-sf-latin --no-sf-vwf   # retail font
    python src/injection_tools/build.py --sf-vwf=0     # same, explicit

SF_VWF needs SF_LATIN (NEEDS below): the kit draws from the latin page.

A tool that injects bytes *for* a gated subsystem should ask `features.on()`
rather than assume the gate: the two sides then can never disagree.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, 'build', 'features.inc')

# name -> (asm define, default, what it gates)
GATES = {
    'SF_VWF': ('SF_VWF', True,
               'the small-font VWF kit (recorder, sorter stubs, FONT.BIN anchor, '
               'per-overlay renderer + data)'),
    'SF_LATIN': ('SF_LATIN', True,
                 'the LATIN CELLS of the small font page (a..z and the two '
                 'punctuation marks, drawn over rare hiragana). Not the kit: '
                 'this is what makes the retail renderer print latin at all, '
                 'so it stays on when SF_VWF is off'),
    'SF_NOCLEAR': ('SF_NOCLEAR', False,
                   'DIAGNOSTIC: the kit records and draws but never clears the '
                   'map cells it claimed. Off in every real build - it leaves '
                   'stale rows on screen. It exists to tell "the clearing pass '
                   'eats this" from "our sprites cover this"'),
    'DIAG': ('SF_DIAG', False,
             'diag counters in the kit state (sf_state: entry count + the last '
             'sort\'s bg/ot/pri) - inspect them with gdb, nothing reads them'),
}


# gate -> gates it needs. A dependency that is off is a build error, never a
# silent half-subsystem: the kit's widths and atlas assume the latin cells.
NEEDS = {'SF_VWF': ('SF_LATIN',)}


def check(gates):
    """Refuse an impossible combination and name it."""
    for gate, needs in NEEDS.items():
        if not gates.get(gate):
            continue
        for need in needs:
            if not gates.get(need):
                raise SystemExit(f'features: {gate} needs {need} - the kit draws '
                                 f'from the latin page, so the two cannot disagree')


def _flag(gate):
    """SF_KIT -> sf-kit (the CLI spelling)."""
    return gate.lower().replace('_', '-')


def from_argv(argv):
    """{gate: bool} from `--no-<gate>`, `--<gate>=0/off` (anything else = the default)."""
    gates = {g: d for g, (_d, d, _w) in GATES.items()}
    argv = ['--no-sf-vwf' if a == '--no-sf-kit' else a for a in argv]   # old spelling
    for arg in argv:
        if not arg.startswith('--'):
            continue
        body = arg[2:]
        value = None
        if '=' in body:
            body, value = body.split('=', 1)
        for gate in GATES:
            if body == 'no-' + _flag(gate):
                gates[gate] = False
            elif body == _flag(gate):
                gates[gate] = (value or '1').lower() not in ('0', 'off', 'no', 'false')
    return gates


def write(gates=None):
    """Write build/features.inc (every gate, so the asm never reads an undefined name)."""
    gates = dict(gates or {g: d for g, (_d, d, _w) in GATES.items()})
    check(gates)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    lines = [';; generated by src/injection_tools/features.py - do not edit',
             ';; one line per feature gate; 0 = the subsystem contributes no bytes at all']
    for gate, (name, _default, what) in GATES.items():
        lines.append(f'{name} equ {1 if gates[gate] else 0}   ; {what}')
    open(OUT, 'w', newline='\n').write('\n'.join(lines) + '\n')
    return gates


def on(gate):
    """The gate as the last build set it (True when build/features.inc absent)."""
    try:
        text = open(OUT, encoding='utf-8').read()
    except FileNotFoundError:
        return GATES[gate][1]
    name = GATES[gate][0]
    m = re.search(rf'^{re.escape(name)}\s+equ\s+([01])\b', text, re.M)
    return bool(int(m.group(1))) if m else GATES[gate][1]


def describe(gates):
    return ', '.join(f'{g}={"on" if v else "off"}' for g, v in gates.items())


if __name__ == '__main__':
    gates = from_argv(sys.argv[1:])
    write(gates)
    print(f'features: {describe(gates)} -> {OUT}')
