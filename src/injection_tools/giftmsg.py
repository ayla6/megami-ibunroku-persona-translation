"""Velvet Room Persona-gift speech ("呼び覚まされたる古き心のカタチ ..." after a maxed Persona is erased).

  python tools/giftmsg.py      write build/giftmsg.asm (included in the ADV section of main.asm)

Original: 3 pages in ADV.BIN at RAM 0x800BB544..0x800BB5C0 (124 bytes, no room for English) printed by the function
0x800A4268 (0x800A4478: a0 = s1-0x15, jal 0x800666DC). That function builds the message IN PLACE every time: it stores the id
of the erased Persona into the parameter byte of <FF0C> (0x800BB559) and the 2-byte id of the item it is turned into into
the two <FF09> parameters (0x800BB58B/C and 0x800BB5B1/2) with a long, repetitive instruction sequence
(0x800A4348..0x800A4468, 72 words). The block also adds, commits and compacts
the gift item. This tool preserves those original inventory instructions, puts the English message in
the bytes it frees (a `j` over the text, then the text), moves the stores into the old Japanese message area
(0x800BB544..0x800BB5C1, zeroed first) and jumps back to 0x800A4468.  That leaves the whole rewritten store sequence
free for the message, which the five-page PSP-US speech needs and the old 212-byte window could not hold.  The stores
are pointed at the new parameter positions.
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import toolbelt  # noqa: E402
import etext      # noqa: E402
import tstatus    # noqa: E402

ROOT = etext.ROOT
B = 0x800643C4
START, END = 0x800A4348, 0x800A4468
TEXT_START = START + 8          # `j gift_code` + delay slot
ROOM = END - TEXT_START         # the message owns the rest of the window
OLD_A, OLD_E = 0x800BB544, 0x800BB5C1
INVENTORY_WORDS = (
    0x00128180, 0x3c01801f, 0x02010821, 0x90221dc4,
    0x00000000, 0x00021040, 0x3c01800c, 0x2421aa92,
    0x00220821, 0x94240000, 0x0c023b47, 0x34050001,
    0x0c023bcb, 0x00000000, 0x0c023c2d, 0x00000000,
)
TSV = os.path.join(ROOT, 'translation', 'manual', 'strings', 'GIFTMSG.tsv')
OUT = os.path.join(ROOT, 'build', 'giftmsg.asm')


def dump():
    import toolbelt
    toolbelt.route_gaps(toolbelt.rel_for(os.path.join(ROOT, 'data', 'psx', 'ADV.BIN')), [hex(OLD_A - B)])
    print(f'giftmsg: row {hex(OLD_A - B)} queued -> {toolbelt.man_path(toolbelt.rel_for(os.path.join(ROOT, 'data', 'psx', 'ADV.BIN')))}')


def main():
    if len(sys.argv) > 1 and sys.argv[1] == 'dump':
        dump()
        return
    d = open(os.path.join(ROOT, 'data', 'psx', 'ADV.BIN'), 'rb').read()
    import toolbelt
    _rows = {r['pos']: r for r in toolbelt.merged_rows(toolbelt.rel_for(os.path.join(ROOT, 'data', 'psx', 'ADV.BIN')))}
    en = (_rows.get(hex(OLD_A - B), {}).get('en') or '').strip()
    if not en:
        os.makedirs(os.path.dirname(OUT), exist_ok=True)
        open(OUT, 'w', encoding='utf-8', newline='\n').write(';; no manual English for the Persona gift message yet\n')
        print('giftmsg: no manual English, leaving the original message untouched')
        return
    import vwf_wrap
    # THE ROW IS THE ONLY WRITE: encode the manual text verbatim, never
    # re-lay it here. The row carries its layout (the shared flow laid its
    # pages once, with the insert widths priced); this check fails loud when
    # a wording edit outgrows a page instead of quietly moving its breaks:
    # three lines a page, every line within the box at the WIDEST item /
    # Persona / nickname the engine can insert (insert_widths.tsv).
    for i, page in enumerate(en.split('<FF04>'), 1):
        lines = [l for l in page.replace('<FF02>', '<FF03>')
                 .replace('<FF01>', '').split('<FF03>')
                 if l.strip()]
        if len(lines) > 3:
            raise SystemExit(f'giftmsg: page {i} has {len(lines)} lines, '
                             f'max 3: {lines}')
        for l in lines:
            px = vwf_wrap.text_width(l)
            if px > vwf_wrap.BOX_WIDTH:
                raise SystemExit(f'giftmsg: page {i} line {px}px > '
                                 f'{vwf_wrap.BOX_WIDTH}px: {l!r}')
    data = etext.encode(en)                       # + FF01
    str_addr = TEXT_START
    code_addr = OLD_A
    room = ROOM
    if len(data) > room:
        raise SystemExit(f'giftmsg: {len(data)} bytes, room {room}')
    if struct.unpack_from(f'<{len(INVENTORY_WORDS)}I', d, START - B) != INVENTORY_WORDS:
        raise SystemExit('giftmsg: retail inventory sequence changed; cannot safely relocate it')
    # parameter positions inside the new string
    p_persona = data.index(b'\xff\x0c') + 2
    p_item = [i + 2 for i in range(len(data) - 3) if data[i] == 0xFF and data[i + 1] == 0x09]
    assert len(p_item) == 2
    P = str_addr + p_persona
    I1, I2 = str_addr + p_item[0], str_addr + p_item[1]
    lines = [';; generated by tools/giftmsg.py - do not edit',
             f'.org {OLD_A:#x}', f'.fill {OLD_E - OLD_A}, 0',
             f'.org {START:#x}', f'.fill {END - START}, 0',
             f'.org {START:#x}',
             f'    j       gift_code', '    nop',
             'gift_text:   ; ' + str(len(data)) + ' bytes, ' + str(room) + ' available',
             '    .byte ' + ', '.join(f'0x{x:02X}' for x in data),
             f'.org {code_addr:#x}',
             f'.area {OLD_E - OLD_A}',
             'gift_code:',
             # Move the retail table-base LUI into the LBU load-delay slot;
             # the remaining original inventory instructions are unchanged.
             '    .word ' + ', '.join(f'{word:#010x}' for word in INVENTORY_WORDS[:4]),
             '    lui     at, 0x800C',
             '    sll     v0, v0, 1',
             '    .word ' + ', '.join(f'{word:#010x}' for word in INVENTORY_WORDS[7:]),
             '    lui     at, 0x801F',
             '    addu    at, s0, at',
             '    lbu     v0, 0x1DC4(at)             ; id of the Persona / item slot',
             '    lui     s1, 0x800A',
             f'    addiu   s1, s1, {P - 0x800A0000:#x}          ; <FF0C> parameter (a0 = s1 - offset below)',
             '    sb      v0, 0(s1)',
             '    sll     v0, v0, 1',
             '    lui     at, 0x800C',
             '    addu    at, at, v0',
             '    lbu     v0, -0x556E(at)',
             '    lbu     v1, -0x556D(at)',
             f'    sb      v0, {I1 - P}(s1)',
             f'    sb      v1, {I1 + 1 - P}(s1)',
             f'    sb      v0, {I2 - P}(s1)',
             f'    j       {END:#x}',
             f'    sb      v1, {I2 + 1 - P}(s1)',
             '.endarea',
             '.org 0x800A4478',
             f'    addiu   a0, s1, {-(P - str_addr)}']
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, 'w', newline='\n').write('\n'.join(lines) + '\n')
    print(f'giftmsg: {len(data)} bytes of {room}; persona param {P:#x}, items {I1:#x} {I2:#x}')


if __name__ == '__main__':
    main()
