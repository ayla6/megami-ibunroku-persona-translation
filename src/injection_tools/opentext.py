"""Title-screen LOAD GAME screens: memory-card messages (OPEN.EXE) and the SLOT 1 / SLOT 2 buttons (OPEN.BIN atlas).

  python tools/opentext.py     write build/open_exe.asm, build/gfx/open_474C0.bin (+ preview PNG)

Messages: OPEN.EXE RAM 0x800A0134.. (file offset = RAM - 0x800A0000 + 0x20800), 11 blocks of 16-bit glyph indices printed
into a COLS x ROWS grid of 16 px cells by 0x80085C30 / 0x800861D0 (cols/rows per block below, from the callers). English uses
the full-width Latin glyphs of the game font (A = 0xA6, a = 0x723.., blank = 0) and has to fit the grid: <= COLS characters
per row. The file number of the "file N is corrupted" message is drawn by the code over the cell where the Japanese has
the placeholder "０" (index 5 of row 1), so that cell stays "０".
Buttons: OPEN.BIN TIM 0x474C0 (4bpp 256x32, VRAM 704,256), row 2 holds the bitmap "スロット1" / "スロット2" (also used for the
tab on the save list). "SLOT 1/2" is composed from the letters of the same atlas, coloured with the gradient of the
original kana and shadowed in black one pixel down-right; tools/buttonlabel.py owns that artwork, and ADV's slot header
cells (tools/menu_gfx.py) draw the identical label.
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import buttonlabel  # noqa: E402
import etext        # noqa: E402
import tim          # noqa: E402
import menu_gfx     # noqa: E402
import strlib       # noqa: E402

ROOT = tim.ROOT
NL = chr(10)
FO = lambda ram: ram - 0x800A0000 + 0x20800

# (RAM, cols, rows, [English rows])
# layout (ram, cols, rows); message text lives in glossary.tsv (opentext),
# lines split on the U+00A6 sentinel. (0x800A0214's 0 is the placeholder
# cell at line index 5.)
LAYOUT = [
    (0x800A0134, 12, 2), (0x800A0164, 13, 1), (0x800A0180, 12, 1),
    (0x800A0198, 13, 2), (0x800A01CC, 12, 3), (0x800A0214, 12, 2),
    (0x800A0244, 12, 1), (0x800A025C, 11, 2), (0x800A0288, 10, 2),
    (0x800A02B0, 10, 2), (0x800A02D8, 13, 3),
]
# A block's grid may not write into the next block's first glyph: the
# assembler would place two writers on the same halfword and the later one
# would silently truncate the earlier message. Slots are contiguous.
for (_ram, _cols, _rows), (_next, *_rest) in zip(LAYOUT, LAYOUT[1:]):
    if _cols * _rows * 2 > _next - _ram:
        raise SystemExit(f'opentext: block {_ram:#x} is {_cols}x{_rows} cells, '
                         f'past the next block at {_next:#x}')
MSGS = [(ram, cols, rows, strlib.glossary('opentext')[f'{ram:#x}'].split('\u00a6'))
        for ram, cols, rows in LAYOUT]
EXTRA = {'.': '．', '?': '？', '!': '！', '-': '－', "'": '’', ',': '，'}


def glyph(c):
    if c == ' ':
        return 0
    if 'A' <= c <= 'Z':
        return etext.char2g[chr(0xFF21 + ord(c) - 65)]
    if 'a' <= c <= 'z':
        return etext.char2g[chr(0xFF41 + ord(c) - 97)]
    if '0' <= c <= '9':
        return etext.char2g[chr(0xFF10 + ord(c) - 48)]
    return etext.char2g[EXTRA[c]]


def messages():
    d = open(os.path.join(ROOT, 'data', 'psx', 'EXE', 'OPEN.EXE'), 'rb').read()
    out = [';; generated by tools/opentext.py - do not edit' + NL]
    for ram, cols, rows, lines in MSGS:
        assert len(lines) == rows, hex(ram)
        ws = []
        for ln in lines:
            if len(ln) > cols:
                raise SystemExit(f'opentext: {ln!r} is {len(ln)} chars, {cols} columns')
            ws += [glyph(c) for c in ln.ljust(cols)]
        n = cols * rows
        out.append(f'; {" / ".join(lines)}{NL}.org OPEN_EXE_ADDR + {FO(ram):#x}{NL}    .halfword ' + ', '.join(f'{w:#x}' for w in ws) + NL)
    open(os.path.join(ROOT, 'build', 'open_exe.asm'), 'w', newline=NL).write(''.join(out))


def buttons():
    from PIL import Image
    d = open(tim.locate('OPEN.BIN'), 'rb').read()
    t = tim.parse(d, 0x474C0)
    w, h = t['px_w'], t['h']
    pix = menu_gfx.unpack(d, t)
    for y in range(16, 32):
        for x in range(0, 100):
            pix[y * w + x] = 0
    ends = [buttonlabel.draw(pix, w, cell + (48 - buttonlabel.width(text)) // 2, 19, text)
            for cell, text in ((0, 'SLOT 1'), (48, 'SLOT 2'))]   # one 48px button cell each, centred
    e1, e2 = ends
    assert e1 < 48 and e2 < 96, (e1, e2)
    os.makedirs(os.path.join(ROOT, 'build', 'gfx'), exist_ok=True)
    open(os.path.join(ROOT, 'build', 'gfx', 'open_474C0.bin'), 'wb').write(menu_gfx.pack(pix))
    # Palette entry zero is transparent. Retail also leaves entry 15 zero,
    # so using it for the shadow otherwise draws holes, not black.
    clut = bytearray(d[t['clut']['at']:t['clut']['at'] + t['clut']['n'] * 2])
    struct.pack_into('<H', clut, 15 * 2, 0x8000)  # opaque PSX black
    open(os.path.join(ROOT, 'build', 'gfx', 'open_474C0_clut.bin'), 'wb').write(clut)
    im = Image.frombytes('P', (w, h), bytes(pix))
    pal = tim.palette(d, t)
    flat = [c for rgb in pal for c in rgb]
    im.putpalette(flat + [0] * (768 - len(flat)))
    im.convert('RGB').resize((w * 4, h * 4), Image.NEAREST).save(os.path.join(ROOT, 'build', 'previews', 'translation', 'open_474C0_preview.png'))
    print(f'opentext: buttons drawn (SLOT 1 ends x={e1}, SLOT 2 ends x={e2}); data at {t["at"]:#x}')


if __name__ == '__main__':
    messages()
    buttons()
    print(f'opentext: {len(MSGS)} messages')
