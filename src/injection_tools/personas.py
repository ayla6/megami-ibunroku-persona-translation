"""Persona names (master table in SLPS_005.00): battle skill menu header, PRS-CHG, party status, field menus ...

  python tools/personas.py dump     write/refresh translation/manual/SLPS_005.00/PERSONAS.tsv (keeps the `en` and `note` columns)
  python tools/personas.py build    QA + generate build/personas.asm (included by main.asm, SLPS section)

Layout: 100 records of 0x2C bytes; record of id k (1-based) = 0x8004B0CC + k*0x2C (record 0 is blank); the name is a
10-byte field at +8 (small-font single-byte glyphs like the skill names, tools/skills.py), FF-terminated unless 10 long.
Bytes +0x29..+0x2B are zero in every record and no reader uses them (readers: whole-record word copies at
SLPS 0x80015DE0 / ADV 0x8009F928, 0x800B1040 / BTLP 0x80087AD0, and single fields): they hold the tail of names
longer than 10 glyphs, like the skill records (inline up to 3 glyphs, FE + offset into persona_tails_x for more).
When a Persona is obtained the whole record is copied into the party data (battle copy 0x8005CDA8 + slot*0x48:
+0x1E id, +0x1F name), so saves made before this patch keep the old name in that copy: patched screens should read
the name through the id (persona_name_copy), not from the copy.
English: official names of the 2009 PSP release (megamitensei wiki), max MAXLEN glyphs.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import toolbelt  # noqa: E402
import etext   # noqa: E402
import skills  # noqa: E402

ROOT = etext.ROOT
BASE = 0x80010000 - 0x800
REC0 = 0x8004B0CC
STRIDE = 0x2C
COUNT = 100
NAME = 8
FIELD = 10
SPARE = 0x29
MAXLEN = 16
TSV = os.path.join(ROOT, 'translation', 'manual', 'SLPS_005.00', 'PERSONAS.tsv')
OUT = os.path.join(ROOT, 'build', 'personas.asm')
OUT_X = os.path.join(ROOT, 'build', 'persona_tails.asm')
NL = chr(10)


def records():
    d = open(os.path.join(ROOT, 'data', 'psx', 'SLPS_005.00'), 'rb').read()
    out = []
    for k in range(1, COUNT + 1):
        a = REC0 + k * STRIDE
        assert d[a + SPARE - BASE:a + SPARE + 3 - BASE] == b'\0\0\0', k
        f = d[a + NAME - BASE:a + NAME + FIELD - BASE]
        out.append((k, a, ''.join(etext.glyph.get(x, '<%02X>' % x) for x in f.split(b'\xff')[0])))
    return out


def record_en():
    """{record id: en} from the canonical SLPS rows (pos = record offset,
    manual wins - toolbelt.merged_rows). The one source for Persona names;
    the rows are scaffolded by slps.py dump and ported by boot_tables."""
    import toolbelt
    by_off = {}
    for r in toolbelt.merged_rows('SLPS_005.00'):
        t = (r.get('en') or '').strip()
        if t:
            for _entry, off in toolbelt.pos_offsets(r['pos']):
                by_off[off] = t
    return {k: by_off.get(a - BASE, '') for k, a, _ja in records()}


def dump():
    """Queue the family's positions in the canonical manual worklist (the
    rows themselves are scaffolded by slps.py dump)."""
    import toolbelt
    toolbelt.route_gaps('SLPS_005.00',
                        [hex(a - BASE) for _k, a, _ja in records()])
    print('personas: worklist queued in', toolbelt.man_path('SLPS_005.00'))


def build():
    en = record_en()
    x = b''
    n = 0
    with open(OUT, 'w', newline=NL) as o:
        o.write(';; generated by tools/personas.py build - do not edit' + NL)
        for k, a, ja in records():
            t = en.get(k, '').strip()
            if not t:
                continue
            if len(t) > MAXLEN:
                raise SystemExit(f'personas: {k} {t!r} is {len(t)} chars, max {MAXLEN}')
            b = skills.encode_glyphs(k, t)
            head = b[:FIELD]
            if len(b) < FIELD:
                head += b'\xff'
            head += bytes(FIELD - len(head))
            o.write(f'; {k} {t}{NL}.org {a + NAME:#x}{NL}    .byte ' + ', '.join(f'0x{c:02X}' for c in head) + NL)
            tail = b[FIELD:]
            if tail:
                if len(tail) <= 3:
                    spare = (tail + b'\xff\x00\x00')[:3]
                else:
                    spare = bytes([0xFE, len(x), 0])
                    x += tail + b'\xff'
                o.write(f'.org {a + SPARE:#x}{NL}    .byte ' + ', '.join(f'0x{c:02X}' for c in spare) + NL)
            n += 1
    with open(OUT_X, 'w', newline=NL) as o:
        o.write(';; generated by tools/personas.py build - tails of 4+ glyphs (offsets from persona_tails_x)' + NL)
        if x:
            o.write('    .byte ' + ', '.join(f'0x{c:02X}' for c in x) + NL)
    print(f'personas: {n}/{COUNT} translated ({len(x)} bytes overflow tails) -> {OUT}')


if __name__ == '__main__':
    sys.stdout.reconfigure(encoding='utf-8')
    {'dump': dump, 'build': build}[sys.argv[1] if len(sys.argv) > 1 else 'build']()
