"""ADV shop lists with the PSP items (--mods=psp-items-and-skills) -> build/shops_adv.asm.

  python src/mods/psp-items-and-skills/shops.py        generate (main.asm includes it under MOD_PSP_ITEMS_AND_SKILLS)
  python src/mods/psp-items-and-skills/shops.py -v     also print every list

Layout (ADV.BIN): table 0x800BABA8 = (count u8, start u8) for 17 lists;
item ids (u16, 1-based) from 0x800BA888 and buy prices (u32) from
0x800BA34C, indexed by start + n (copied at shop open by 0x800AAFE0 /
0x800AB068 into 0x800EB590 / 0x800EB5D0, room for SHOP_MAX entries).
A list that is the start of another list (list 10 = the first 10 of
list 11, 12 = the first 10 of 13) shares that window, which frees enough
entries for the additions while the arrays keep their size (ITEM_CAP).

How a room opens a shop: event-script command `FF 2A <store> 00` calls
the shop function 0x80099304(store); STORE table 0x800BAB5C = (menu type
u8, list u8) x 38. Consumable lists (menu type 2) 10, 11 and 16 are the
Satomi Tadashi pharmacies (Tadashi's dad, Sato-chan's store, Tadashi's
uncle); 10 and 11 are also the Snow Queen route's school pharmacy.
"""
import os
import struct
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
import toolpath  # noqa: E402,F401  (every tool folder on sys.path)
import toolbelt  # noqa: E402

ROOT = toolbelt.ROOT
ADV = os.path.join(ROOT, 'data', 'psx', 'ADV.BIN')
OUT = os.path.join(ROOT, 'build', 'shops_adv.asm')
CONSTANTS = os.path.join(ROOT, 'src', 'mods', 'psp-items-and-skills', 'pspitems.inc')
BASE = 0x800643C4
TABLE, ITEMS, PRICES = 0x800BABA8, 0x800BA888, 0x800BA34C
SHOPS = 17
ITEM_CAP = 178                  # entries in the retail arrays (the item array is followed by the 2nd shop table)
SHOP_MAX = 24                   # copy buffer 0x800EB5D0.. reaches the next variable at 0x800EB630
PRICE = 10000                   # both items, as on the PSP
PHARMACIES = (10, 11, 16)
NL = chr(10)


def additions():
    """list -> [(insert position, 1-based item id, price)]: Clean Salt, then
    Emergency Exit, after the list's tenth entry (lists 10 / 11) or its
    eighth (list 16) - right behind the retail consumables."""
    salt = toolbelt.asm_equ('PSP_ES_ITEM', CONSTANTS) + 1
    exit_ = toolbelt.asm_equ('PSP_TR_ITEM', CONSTANTS) + 1
    at = {10: 10, 11: 10, 16: 8}
    return {s: [(at[s], salt, PRICE), (at[s], exit_, PRICE)] for s in PHARMACIES}


def read():
    d = open(ADV, 'rb').read()
    shops = []
    for s in range(SHOPS):
        n, st = d[TABLE - BASE + 2 * s], d[TABLE - BASE + 2 * s + 1]
        shops.append([(struct.unpack_from('<H', d, ITEMS - BASE + 2 * (st + i))[0],
                       struct.unpack_from('<I', d, PRICES - BASE + 4 * (st + i))[0]) for i in range(n)])
    return shops


def build():
    shops = read()
    adds = additions()
    for s, items in adds.items():
        # same position: inserted in reverse, so the first one ends up first
        for pos, item, price in reversed(items):
            if item in [i for i, _ in shops[s]]:
                raise SystemExit(f'shops: list {s} already sells item {item}')
            shops[s].insert(pos, (item, price))
    # pack: longest lists first; a list that is the start of a placed one shares its window
    flat, where = [], {}
    for s in sorted(range(SHOPS), key=lambda k: -len(shops[k])):
        lst = shops[s]
        if len(lst) > SHOP_MAX:
            raise SystemExit(f'shops: list {s} has {len(lst)} entries > {SHOP_MAX}')
        for t, st in where.items():
            if shops[t][:len(lst)] == lst:
                where[s] = st
                break
        else:
            where[s] = len(flat) if lst else 0
            flat += lst
    if len(flat) > ITEM_CAP:
        raise SystemExit(f'shops: {len(flat)} entries > {ITEM_CAP}')
    flat += [(0, 0)] * (ITEM_CAP - len(flat))
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', newline=NL) as o:
        o.write(';; generated by src/mods/psp-items-and-skills/shops.py - do not edit' + NL)
        o.write(f'.org 0x{TABLE:08X}' + NL)
        for s in range(SHOPS):
            o.write(f'    .byte {len(shops[s])}, {where[s]}' + NL)
        o.write(f'.org 0x{ITEMS:08X}' + NL)
        for i in range(0, ITEM_CAP, 12):
            o.write('    .halfword ' + ', '.join(str(x) for x, _ in flat[i:i + 12]) + NL)
        o.write(f'.org 0x{PRICES:08X}' + NL)
        for i in range(0, ITEM_CAP, 8):
            o.write('    .word ' + ', '.join(str(p) for _, p in flat[i:i + 8]) + NL)
    used = len([x for x in flat if x[0]])
    print(f'shops: {sum(len(v) for v in adds.values())} additions, {used}/{ITEM_CAP} array entries -> '
          f'{os.path.relpath(OUT, ROOT)}')
    return shops, where


if __name__ == '__main__':
    shops, where = build()
    if '-v' in sys.argv:
        for s in range(SHOPS):
            print(s, where[s], [i for i, _ in shops[s]])
