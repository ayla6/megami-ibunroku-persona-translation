"""Clean Salt / Estoma (--mods=psp-items-and-skills): the strongest demon level of every
battle formation -> build/estoma_levels.asm (mods/psp-items-and-skills/dng.asm and
mods/psp-items-and-skills/s2d.asm include it).

  python src/mods/psp-items-and-skills/estoma.py        generate
  python src/mods/psp-items-and-skills/estoma.py -v     also print every formation

Formation data: the dungeon writes the formation id (u16) to 0x801F5350;
BTLP 0x80087D60 loads its chunk of /B/D.BIN (sector offsets: u16 table BTLP
0x800DB9A0, chunk f = sectors t[f]..t[f+1], loaded to 0x80140000) and
reads 9 slots of 2 bytes from BTLP 0x800E8850 + f * 18 (position, entry
index n; 0 = empty). Entry n = u32 pointer at chunk + (n - 1) * 8 (RAM
address in the 0x80140000 image); the demon id is the high byte of the u16
at that pointer + 2. Demon level = SLPS demon record 0x800417A0 + id *
0x38, byte +0x0A. An empty formation gets 255: never skipped.
"""
import os
import struct
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
import toolpath  # noqa: E402,F401  (every tool folder on sys.path)
import toolbelt  # noqa: E402

ROOT = toolbelt.ROOT
PSX = os.path.join(ROOT, 'data', 'psx')
OUT = os.path.join(ROOT, 'build', 'estoma_levels.asm')
CONSTANTS = os.path.join(ROOT, 'src', 'mods', 'psp-items-and-skills', 'pspitems.inc')
BTLP_BASE = 0x800643C4
SLPS_BASE = 0x80010000 - 0x800
SECTORS, SLOTS = 0x800DB9A0, 0x800E8850
DEMONS, DEMON_STRIDE, LEVEL = 0x800417A0, 0x38, 0x0A
CHUNK_ADDR = 0x80140000
NL = chr(10)


def formations():
    count = toolbelt.asm_equ('ES_FORMATIONS', CONSTANTS)   # BTLP 0x8008011C: ids >= it become 0x10
    b = open(os.path.join(PSX, 'BTLP.BIN'), 'rb').read()
    t = [struct.unpack_from('<H', b, SECTORS - BTLP_BASE + 2 * i)[0] for i in range(count + 1)]
    out = []
    with open(os.path.join(PSX, 'B', 'D.BIN'), 'rb') as dbin:
        for f in range(count):
            dbin.seek(t[f] * 2048)
            ch = dbin.read((t[f + 1] - t[f]) * 2048)
            ids = []
            for k in range(9):
                n = b[SLOTS - BTLP_BASE + f * 18 + 2 * k + 1]
                if not n:
                    continue
                p = struct.unpack_from('<I', ch, (n - 1) * 8)[0] - CHUNK_ADDR
                ids.append(struct.unpack_from('<H', ch, p + 2)[0] >> 8)
            out.append(ids)
    return out


def main():
    forms = formations()
    s = open(os.path.join(PSX, 'SLPS_005.00'), 'rb').read()
    level = lambda i: s[DEMONS + i * DEMON_STRIDE + LEVEL - SLPS_BASE]
    top = [max((level(i) for i in ids), default=255) for ids in forms]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', newline=NL) as o:
        o.write(';; generated by src/mods/psp-items-and-skills/estoma.py - strongest demon level per formation '
                '(255 = empty / never skip)' + NL)
        for i in range(0, len(top), 20):
            o.write('    .byte ' + ', '.join(str(x) for x in top[i:i + 20]) + NL)
        o.write('.align 4' + NL)
    print(f'estoma: {len(forms)} formations, {sum(1 for ids in forms if not ids)} empty -> '
          f'{os.path.relpath(OUT, ROOT)}')
    if '-v' in sys.argv:
        for f, ids in enumerate(forms):
            print(f, top[f], ' '.join(f'{i}:{level(i)}' for i in ids))


if __name__ == '__main__':
    main()
