;; -------------------------------------------------------------
;; vwf_glyph_map_small(a0 = glyph code, a1 = 1 on the name-insertion path) - the body of
;; slps_005.00/party_name_vwf.asm's vwf_glyph_map_party, which the engine calls directly.
;; Name insertions (<FF13> arcana, <FF0C> Persona / demon / item names ...) copy small-font table bytes, whose
;; English letters are small-font codes, not VWF bytes: map them through vwf_small_map. Everything else (and
;; unmapped codes, i.e. Japanese) goes on to vwf_name_map. Returns v0; clobbers t0-t6 like vwf_name_map.
;; -------------------------------------------------------------
vwf_glyph_map_small:                    ; entries 0xD0..: small-font cells -> ASCII
    ;; The sole caller, vwf_glyph_map_party, already checked a1 != 0.
    sltiu   t0, a0, VWF_SMALL_MAP_LEN
    beqz    t0, @@other
    srl     t1, a0, 3                   ; (delay slot) 8-byte page index
    la      t2, vwf_small_pages
    addu    t1, t2, t1
    lbu     t1, 0(t1)                  ; zero = unpopulated page
    andi    t3, a0, 7                   ; (load-delay filler)
    beqz    t1, @@other
    addiu   t1, t1, vwf_small_map - vwf_small_pages - 1
    addu    t1, t1, t2
    addu    t1, t1, t3
    lbu     t1, 0(t1)
    nop
    beqz    t1, @@other
    nop
    jr      ra
    addiu   v0, t1, VWF_CHAR_BIAS
@@other:
    j       vwf_name_map
    nop

