;; =============================================================
;; SLPS_005.00 - full-length Persona names (tools/personas.py)
;;
;; Same scheme as skill_names.asm: the master record (0x8004B0CC + id*0x2C)
;; keeps the first 10 glyphs at +8; longer names continue in the unused
;; bytes +0x29..+0x2B (up to 3 glyphs) or FE + offset into persona_tails_x.
;; persona_name_copy writes exactly 16 glyphs (name, then blank glyph 0).
;; Reads the master table by id, so Personas obtained before the patch
;; (whose party-data copy of the name is still Japanese) show English too.
;; =============================================================

.org PERSONA_CODE_ADDR
.area PERSONA_CODE_SIZE

;; a0 = destination (16 bytes), a1 = Persona key (master-table index 1..100;
;; record 0 at PERSONA_RECORDS_ADDR is unused). The key is the byte retail
;; indexes its own name reads with: name field 0x8004B0CC + 8 + key*0x2C.
;; clobbers v0, v1, a0, a1, a2, at only (same contract as skill_name_copy)
persona_name_copy:
    sll     v0, a1, 1
    addu    v0, v0, a1
    sll     v0, v0, 2
    subu    v0, v0, a1                  ; id * 11
    sll     v0, v0, 2                   ; id * 0x2C
    la      v1, PERSONA_RECORDS_ADDR + PERSONA_NAME
    addu    v1, v1, v0                  ; v1 = name field
;; a0 = destination, v1 = the record's name field: the same copy, reached
;; with the field pointer the caller already holds (the fusion draw helper's
;; def path). Falls into the shared body; the id math above is skipped, so a
;; direct caller must put the field pointer in v1 itself.
persona_name_copy_at:
    li      a1, PERSONA_FIELD           ; a1 = glyph count where this phase stops
    move    a2, zero                    ; a2 = glyphs written
@@copy:
    beq     a2, a1, @@phase_end
    lbu     v0, 0(v1)                   ; (harmless when the branch is taken)
    li      at, 0xFF
    beq     v0, at, @@pad
    addiu   v1, v1, 1
    sb      v0, 0(a0)
    addiu   a0, a0, 1
    b       @@copy
    addiu   a2, a2, 1
@@phase_end:
    li      at, PERSONA_FIELD
    bne     a2, at, @@pad               ; the tail phase ended
    addiu   v1, v1, PERSONA_SPARE - PERSONA_NAME - PERSONA_FIELD   ; record + 0x29 (harmless if taken)
    lbu     v0, 0(v1)
    li      at, 0xFE
    bne     v0, at, @@copy              ; inline tail: up to 3 glyphs
    li      a1, PERSONA_FIELD + 3
    lbu     v0, 1(v1)
    la      v1, persona_tails_x
    addu    v1, v1, v0
    b       @@copy                      ; overflow tail, FF-terminated
    li      a1, PERSONA_MAXLEN
@@pad:
    li      at, PERSONA_MAXLEN
@@pad_loop:
    beq     a2, at, @@done
    nop
    sb      zero, 0(a0)
    addiu   a0, a0, 1
    b       @@pad_loop
    addiu   a2, a2, 1
@@done:
    jr      ra
    nop

.endarea

.org PERSONA_TAILS_ADDR
.area PERSONA_TAILS_SIZE
persona_tails_x:
.include "../../build/persona_tails.asm"      ; generated by src/injection_tools/personas.py
.endarea

;; The Persona name bank is its own dead-code run, separate from the skill
;; slots; both are ranges of the one ownership bitmap (btl_name_owner.asm:
;; Persona bits 0..2, skill slot i at bit 3+i).
.if PERSONA_HDR_STRIDE != 16 || PERSONA_HDR_BUF + 4 * PERSONA_HDR_STRIDE != PERSONA_HDR_BUF_END || PERSONA_HDR_BUF_END > PERSONA_HDR_LIMIT
    .error "battle Persona name slots must stay inside their own dead run"
.endif
.org PERSONA_HDR_BUF
.area 64
    .fill 64, 0
.endarea

;; The battle skill-menu header's "Cost" label: a static row whose string is
;; the Persona bank's fourth slot. It is outside the owned Persona range, so
;; the descriptor at BTLP_HDR_LABEL_DESC draws it through the retail
;; fixed-width path.
.if BATTLE_LABEL_BUF != PERSONA_HDR_BUF + 3 * PERSONA_HDR_STRIDE
    .error "the Cost label slot must sit inside the Persona dead run"
.endif
.org BATTLE_LABEL_BUF
    .byte 0xA8, 0x3A, 0x3E, 0x3F, 0xFF  ; "Cost" (C + lowercase o s t = smallfont_lc.LC_CODES)

;; Register source-proven Persona ID in unit a2 (0..2). a0/a1 and t* survive.
;; The continuation updates the shared slot bitmap, then returns to the caller.
.if PERSONA_VWF_CODE_ADDR + 48 != VWF_BTLP_CODE_ADDR
    .error "Persona registration overlaps resident VWF code"
.endif
.org PERSONA_VWF_CODE_ADDR
.area 48
persona_flag_register:
    sltiu   v0, a1, 101
    beqz    v0, @@invalid
    move    v1, zero
    srl     v0, a1, 3
    la      at, persona_vwf_flags
    addu    at, at, v0
    lbu     v1, 0(at)
    andi    v0, a1, 7
    srlv    v1, v1, v0
@@invalid:
    j       persona_flag_continue
    nop
.endarea
