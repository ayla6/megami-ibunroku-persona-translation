;; =============================================================
;; SLPS_005.00 - full-length skill names (tools/skills.py)
;;
;; A skill record (0x80047D44 + id*0x14) keeps the first 10 glyphs of the
;; English name. Longer names continue in the record's unused bytes
;; +0x11..+0x13 (up to 3 glyphs, FF-terminated when shorter) or, for longer
;; tails, FE + offset into skill_tails_x (glyphs + FF).
;; skill_name_copy writes the name followed by an FF terminator (exactly
;; SKILL_MAXLEN glyphs when the name fills the slot).
;; Lives in an unreferenced SLPS function (tools/deadfuncs.py), resident.
;; =============================================================

.org SKILL_CODE_ADDR
.area SKILL_VWF_FLAGS_ADDR - SKILL_CODE_ADDR

;; a0 = destination (SKILL_MAXLEN bytes), a1 = skill id (1-based)
;; Writes the name and one FF terminator, or exactly SKILL_MAXLEN glyphs when
;; the name fills the slot. The battle text renderer ends a line at FF, so a
;; short name costs only its own glyphs, never blank padding.
;; clobbers v0, v1, a0, a1, a2, at only (callers rely on this: t*/a3 are live)
skill_name_copy:
    addiu   sp, sp, -8
    sw      t0, 0(sp)
    b       skill_copy_common
    li      t0, SKILL_MAXLEN            ; callers own a SKILL_MAXLEN-byte slot

;; a0 = destination, a1 = skill id, a2 = destination size. Never write more
;; than a2 bytes; callers must still prove the whole name fits before calling.
skill_name_copy_full:
    addiu   sp, sp, -8
    sw      t0, 0(sp)
    move    t0, a2
skill_copy_common:
    sll     v0, a1, 2
    addu    v0, v0, a1
    sll     v0, v0, 2                   ; id * 0x14
    la      v1, SKILL_RECORDS_ADDR
    addu    v1, v1, v0                  ; v1 = record (name field)
    li      a1, SKILL_FIELD             ; a1 = glyph count where this phase stops
    move    a2, zero                    ; a2 = glyphs written
@@copy:
    beq     a2, t0, @@done             ; also bounds head and inline tail
    nop
    beq     a2, a1, @@phase_end
    lbu     v0, 0(v1)                  ; safe RAM read even at a phase end
    li      at, 0xFF
    beq     v0, at, @@pad
    addiu   v1, v1, 1
    sb      v0, 0(a0)
    addiu   a0, a0, 1
    b       @@copy
    addiu   a2, a2, 1
@@phase_end:
    li      at, SKILL_FIELD
    bne     a2, at, @@pad               ; the tail phase ended (13 or 15 glyphs)
    nop
    addiu   v1, v1, SKILL_SPARE - SKILL_FIELD   ; record + 0x11
    lbu     v0, 0(v1)
    li      at, 0xFE
    bne     v0, at, @@copy              ; inline tail: up to 3 glyphs
    li      a1, SKILL_FIELD + 3
    lbu     v0, 1(v1)
    la      v1, skill_tails_x
    addu    v1, v1, v0
    b       @@copy                      ; overflow tail: up to 5 glyphs, FF-terminated
    move    a1, t0
@@pad:
    beq     a2, t0, @@done             ; the name filled the slot: no room for FF
    nop
    li      at, 0xFF
    sb      at, 0(a0)                  ; end the line where the name ends
@@done:
    lw      t0, 0(sp)
    jr      ra
    addiu   sp, sp, 8

.endarea

;; The tail allocation must end exactly before the next resident code owner.
.if SKILL_TAILS_ADDR + SKILL_TAILS_SIZE != AFF_FREE2_ADDR
    .error "skill tails overlap the affinity-free resident code"
.endif

