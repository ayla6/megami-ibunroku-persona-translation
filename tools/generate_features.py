"""Generate webpatcher/features.js from tools/release_options.json.

release_options.json is the single source of option wording: the release
README reads it directly, and this script turns it into the file the page
loads. Run by the Pages workflow, by tools/publish_patches.py for local
serving, and by hand after editing the JSON:

    python tools/generate_features.py

Standard library only, so it runs anywhere the workflow does.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'tools' / 'release_options.json'
TARGET = ROOT / 'webpatcher' / 'features.js'


def generate(source=SOURCE, target=TARGET):
    options = json.loads(Path(source).read_text(encoding='utf-8'))
    if not options:
        raise SystemExit(f'{source} lists no options')
    for item in options:
        for field in ('label', 'name', 'description'):
            if not item.get(field) or not str(item[field]).strip():
                raise SystemExit(f'{source}: an option is missing {field}')
    features = {item['label']: {'name': item['name'],
                                'description': item['description']}
                for item in options}
    target.write_text(
        '/* Generated by tools/generate_features.py from'
        ' tools/release_options.json - edit the JSON, not this file. */\n'
        'globalThis.FEATURES = ' + json.dumps(features, indent=2) + ';\n',
        encoding='utf-8')
    return target


def main():
    print(f'wrote {generate()}')


if __name__ == '__main__':
    main()
