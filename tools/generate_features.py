"""Generate webpatcher/features.js from the mods (src/mods/*/mod.tsv).

Each mod's mod.tsv is the single source of its name and description (read by
src/pipeline/mods.py): the release README and the layers carry the
same wording, and this script turns the released mods into the file the page
loads, listed by name. A mod marked `default` starts ticked on a visit with no remembered
choice. A mod's choices (its option groups and extras) come along as
`choices`, so the page can offer them under the mod; every released always-on mod is
listed (`always`), including the base and alphabet components. Run by the Pages workflow, by tools/publish_patches.py for local
serving, and by hand after editing a mod.tsv:

    python tools/generate_features.py

Standard library only, so it runs anywhere the workflow does.
"""
import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
import os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src'))
import toolpath  # noqa: E402,F401  (every tool folder on sys.path)
import mods  # noqa: E402

TARGET = ROOT / 'webpatcher' / 'features.js'
RENAMED = ROOT / 'src' / 'mods' / 'renamed.tsv'   # old short label -> the mod's slug


def generate(target=TARGET):
    released = mods.released()
    if not released:
        raise SystemExit('src/mods holds no released mod')
    shown = released + [mod for mod in mods.load()
                        if mod.always and mod.release]
    features = {mod.label: {'name': mod.name, 'description': mod.description,
                            **({'author': mod.author} if mod.author else {}),
                            **({'default': True} if mod.default else {}),
                            **({'always': True} if mod.always else {}),
                            **({'warning': mod.warning} if mod.warning else {}),
                            **({'integrates': [{'with': i.other, 'text': i.text}
                                               for i in mod.integrates]}
                               if mod.integrates else {}),
                            **({'ranges': [{'key': r.key, 'minimum': r.minimum, 'maximum': r.maximum,
                                           'step': r.step, 'default': r.default, 'name': r.name,
                                           **({'follows': r.follows} if r.follows else {})}
                                          for r in mod.ranges]} if mod.ranges else {}),
                            **({'choices': [{'token': c.token, 'group': c.group,
                                             'name': c.name, 'description': c.description}
                                            for c in mod.choices]} if mod.choices else {})}
                for mod in sorted(shown, key=lambda mod: (not mod.always, mod.name.lower()))}
    # mods were once known by short labels (`saves`): a visitor's remembered
    # selections and history still say them, so the page maps them once
    with open(RENAMED, encoding='utf-8', newline='') as source:
        renamed = {row['old']: row['new'] for row in csv.DictReader(source, delimiter='\t')}
    target.write_text(
        "/* Generated by tools/generate_features.py from each mod's mod.tsv -"
        ' edit those, not this file. */\n'
        'globalThis.FEATURES = ' + json.dumps(features, indent=2) + ';\n'
        'globalThis.FEATURE_RENAMES = ' + json.dumps(renamed, indent=2) + ';\n',
        encoding='utf-8')
    return target


def main():
    print(f'wrote {generate()}')


if __name__ == '__main__':
    main()
