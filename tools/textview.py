def cmd_file(name):
    key, sd = resolve(name)
    items = build_items(sd.get('psx'), sd.get('psp_jp'), sd.get('psp_us'))
    sides = ' '.join(f'{r}={sd[r]}' for r in REGIONS if sd.get(r))
    print(f'{BOLD}== {key} =={OFF} {DIM}{sides}{OFF} {DIM}({len(items)} items){OFF}\n')
    for it in items:
        print(render(it))
        print()


def cmd_show(name, sel):
    key, sd = resolve(name)
    items = build_items(sd.get('psx'), sd.get('psp_jp'), sd.get('psp_us'))
    title = sd.get('psx') or sd.get('psp_us') or key
    inside = set()          # a selector may be a byte position inside a row
    if not sel.isdigit():
        try:
            off = int(sel, 16)
        except ValueError:
            off = None
        if off is not None:
            for region in REGIONS:
                rel = sd.get(region)
                if rel:
                    row = _covering(_src_index(region, rel), off)
                    if row is not None:
                        inside.add((region, row['id']))
    for it in items:
        sides = [(region, r) for region, r in (('psx', it.psx), ('jp', it.jp),
                                               ('us', it.us)) if r]
        ids = [r['id'] for _rg, r in sides]
        poss = [r['pos'] for _rg, r in sides]
        if sel in ids or sel in poss or any((rg, r['id']) in inside
                                            for rg, r in sides):
            print(render(it, f'{title} #{sel}'))
            return
    sys.exit(f'textview: {key}: no item {sel!r} (ids: '
             f'{", ".join(str(r["id"]) for r in (it.psx, it.jp, it.us) if r)[:60]}...')


def cmd_find(needle):
    """Search every side of every file; matched rows print whole (all data),
    unmatched PSP rows print as orphans - source rows, not gaps."""
    low = needle.lower()
    shown = 0
    for key, sd in sorted(sides_index().items()):
        items = build_items(sd.get('psx'), sd.get('psp_jp'), sd.get('psp_us'))
        for it in items:
            hay = [(r['text'] or '').lower() for r in (it.psx, it.jp, it.us) if r]
            hay += [(it.trans or '').lower(), it.note.lower()]
            if any(low in h for h in hay if h):
                shown += 1
                side = it.psx or it.us or it.jp
                label = f'{sd.get("psx") or sd.get("psp_us")} #{side["id"]}' if side \
                    else f'{sd.get("psx") or sd.get("psp_us") or key} #{(it.gen or it.man)["id"]} (orphan row)'
                print(render(it, label))
                print()
    print(f'{DIM}{shown} items match {needle!r}{OFF}')


def cmd_gaps(name=None):
    """Target items whose current translation is empty (whole tree or one
    file). Source rows - the units that live only on the PSP sides - are
    not targets of translation: never counted, never listed."""
    if name:
        return cmd_missing(name)
    keys = sorted(sides_index())
    n = m = 0
    for key in keys:
        sd = sides_index()[key]
        items = build_items(sd.get('psx'), sd.get('psp_jp'), sd.get('psp_us'))
        todo = [it for it in items if it.target]
        empty = [it for it in todo if not it.trans.strip()]
        n += len(empty)
        m += len(todo)
        if empty:
            print(f'{key:12} {len(empty):4}/{len(todo):<4} {DIM}untranslated{OFF}')
    print(f'{DIM}{n}/{m} items untranslated{OFF}')


