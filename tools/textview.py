MISSING_HELP = """\
usage: textview.py missing [FILE] [options]

The untranslated strings, one entry at a time instead of a count: the
Japanese unit laid out the way the game breaks it (line breaks and page
breaks become real breaks, every control code stays visible), the PSP
Japanese and PSP English wherever a source is known, and the over-cap
draft parked in the manual note.

  FILE            one file (rel, bare name or key); default: every file
  --start N       skip the first N entries (paging)
  --limit N       show at most N entries (0 = all)
  --source        only entries whose PSP source is known
  --no-source     only entries with no PSP source at all (the hunt list)
  --over          only over-cap drafts (the note holds the PSP wording)
  --hunt          for entries with no PSP source, look the Japanese up in
                  the extracted PSP trees by small identifiable fragments
                  (never whole-string: the two sides decode and reword
                  differently) and show the rows that carry parts of it
  --flat          raw single-line text, no layout
  --ids           just the entry/box ids and positions, for scripting
"""

LINE_BREAK = ('<FF03>', '<FFF6>')          # one line ends here
PAGE_BREAK = ('<FFFC><FFFB><FFF7>', '<FFFB><FFF7>', '<FF02>', '<FF04>')
RULE = '·' * 60


def flow(text, flat=False):
    """One unit's text laid out for reading: the game's line breaks become
    line breaks and its page breaks a rule between paragraphs - the text
    is never rewritten, every control code is still there, in its own
    place, and is dimmed at paint time."""
    if flat:
        return [text]
    out, line = [], ''
    i = 0
    while i < len(text):
        tok = None
        for p in PAGE_BREAK + LINE_BREAK:      # longest match first
            if text.startswith(p, i):
                tok = p
                break
        if tok is None:
            m = CODE_RE.match(text, i)
            tok = m.group(0) if m else text[i]
        i += len(tok)
        line += tok
        if tok in LINE_BREAK:
            out.append(line)
            line = ''
        elif tok in PAGE_BREAK:
            if line:
                out.append(line)
            out.append(RULE)
            line = ''
    if line:
        out.append(line)
    out = _collapse(out)
    while out and out[-1] == RULE:
        out.pop()
    while out and out[0] == RULE:
        out.pop(0)
    return out


def _collapse(out):
    """A display line that is nothing but control codes is a marker the
    game put at a break, not text of its own: it stays with the line it
    ended instead of floating alone under the break rule."""
    res = []
    for ln in out:
        if ln != RULE and not CODE_RE.sub('', ln).strip():
            for j in range(len(res) - 1, -1, -1):
                if res[j] != RULE:
                    res[j] += ln
                    break
            else:
                res.append(ln)
        else:
            res.append(ln)
    return res


def _wrap(lines, width, indent):
    """Break long display lines without ever splitting a control code."""
    out = []
    for ln in lines:
        if ln == RULE:
            out.append(ln)
            continue
        while len(ln) > width:
            cut = ln.rfind(' ', indent, width)
            if cut <= indent:
                break
            out.append(ln[:cut])
            ln = ' ' * indent + ln[cut + 1:]
        out.append(ln)
    return out


def gap_reason(it):
    """Why this target is still untranslated - and never a guess.

    A note is a machine's report on the row, so it IS the reason. Reading
    `jp`/`us` as "source known" was wrong twice over: those sides come from
    the row's `psp` pointer, so a pointer that a weak needle match made up
    showed up as a source, and a draft exceeding a layout limit showed up
    as nothing at all."""
    note = it.note.strip()
    if note.startswith('over limit'):
        return 'over-cap draft'
    if note.startswith('characters not allowed'):
        return 'unusable draft (bad characters)'
    if note.startswith('leftover words'):
        return 'empty unit (no Japanese)'
    if note.startswith('psp lead'):
        return 'lead - unverified match'
    if note.startswith('psp '):
        return 'source proven - no wording fits'
    if it.jp or it.us:
        return 'source known'
    return 'no PSP source'


def missing_items(key):
    sd = sides_index()[key]
    items = build_items(sd.get('psx'), sd.get('psp_jp'), sd.get('psp_us'))
    return [it for it in items if it.target and not it.trans.strip()], sd


# ---------------------------------------------------------------------------
# hunt: a unit's Japanese inside the PSP trees, found by small needles
# ---------------------------------------------------------------------------
# The matcher is not a viewer concern - a match is the `psp` pointer, and
# the pointer is what the porters and builders read - so it lives in the
# matching layer and this is only its front end. src/extraction_tools/
# matching/match_jp.py is the one implementation; port_lastresort.py is
# what turns its answers into translation/ rows.

sys.path.insert(0, os.path.join(ROOT, 'src', 'extraction_tools', 'matching'))
import toolbelt  # noqa: E402
import match_jp   # noqa: E402

hnorm = match_jp.norm
hunt_index = match_jp.index
needle_len = match_jp.needle_len


def hunt(ja, want=3):
    """[(rel, row, shared, ratio)] the PSP rows that carry this Japanese.
    `shared` is the count of fragments they share - see match_jp."""
    k = match_jp.norm(ja, psx=True)     # `ja` is a PSX line
    out = []
    for rel, row, _tier, ratio in match_jp.find(ja, want=want):
        t = match_jp.norm(row['text'])
        n = min(match_jp.needle_len(k), match_jp.needle_len(t))
        a = {k[j:j + n] for j in range(len(k) - n + 1)}
        b = {t[m:m + n] for m in range(len(t) - n + 1)}
        out.append((rel, row, len(a & b), ratio))
    return out


def hunt_twin(rel, row):
    """The PSP-US wording of a hunted PSP-JP row, or None where nobody
    proved the twin. A twin that is pure undecoded code placeholders is
    NOT shown as wording - those rows carry no English anyone could read."""
    twin = match_jp.us_twin(rel, row)
    return twin if twin is not None and hnorm(twin['text']) else None

def cmd_missing(name=None, start=0, limit=0, pick=None, flat=False,
                ids=False, do_hunt=False):
    keys = [resolve(name)[0]] if name else sorted(sides_index())
    todo = []
    for key in keys:
        gaps, sd = missing_items(key)
        for it in gaps:
            r = gap_reason(it)
            if pick and r not in pick:
                continue
            todo.append((key, sd, it, r))
    if ids:
        for key, _sd, it, r in todo:
            side = it.psx or it.us or it.jp or it.gen or it.man
            print(f'{key}\t{it.pos}\t{side["id"] if side else ""}\t{r}')
        return
    shown = todo[start:start + limit] if limit else todo[start:]
    if not shown:
        print(f'{DIM}nothing to show ({len(todo)} entries match){OFF}')
        return
    head = f'{len(todo)} untranslated'
    if pick:
        head += f' ({", ".join(sorted(pick))})'
    print(f'{BOLD}{head}{OFF} - showing {start + 1}..{start + len(shown)}\n')
    width = min(__import__('shutil').get_terminal_size().columns, 96)
    for n, (key, sd, it, r) in enumerate(shown, start=start + 1):
        label = it.psx or it.us or it.jp or it.gen or it.man or {}
        where = sd.get('psx') or sd.get('psp_us') or sd.get('psp_jp') or key
        flag = {'over-cap draft': YLW, 'unusable draft (bad characters)': YLW,
                'empty unit (no Japanese)': DIM, 'lead - unverified match': YLW,
                'source proven - no wording fits': GRN, 'source known': GRN,
                'no PSP source': RED}.get(r, DIM)
        print(f'{BOLD}{REV} [{n}/{len(todo)}] {where} #{label.get("id", "?")}'
              f'  pos {it.pos} {OFF} {flag}{r}{OFF}')
        for tag, row in (('ja', it.psx), ('jp', it.jp), ('us', it.us)):
            if row is None:
                continue
            print(f'  {tag:<6}{DIM}{"psx" if tag == "ja" else "psp"}{OFF}')
            for ln in _wrap(flow(row['text'], flat), width, 10):
                print(f'    {DIM}{ln}{OFF}' if ln == RULE
                      else '    ' + paint(ln))
        reason, _, draft = it.note.partition(';')
        if draft.strip():
            print(f'  {"draft":<6}{DIM}{reason.strip()}{OFF}')
            for ln in _wrap(flow(draft.strip(), flat), width, 10):
                print(f'    {YLW}{paint(ln, YLW)}{OFF}')
        elif it.note.strip():
            print(f'  {"note":<6}{RED}{it.note}{OFF}')
        if it.jp is None and it.us is None and not draft.strip():
            if do_hunt:
                ja = (it.psx or {}).get('text', '')
                cands = hunt(ja)
                if not cands:
                    print(f'  {"hunt":<6}{DIM}(no PSP row carries any '
                          f'identifiable fragment){OFF}')
                for n2, (crel, crow, shared, ratio) in enumerate(cands):
                    twin = hunt_twin(crel, crow)
                    mark = GRN if ratio > 0.75 else YLW if ratio > 0.5 else DIM
                    print(f'  {"hunt":<6}{mark}{ratio:.2f}{OFF} '
                          f'{DIM}{shared} needles · {crel} #{crow["id"]} '
                          f'{crow["pos"]}{OFF}')
                    for ln in _wrap(flow(crow['text'], flat), width, 18):
                        print(f'    {DIM}{ln}{OFF}' if ln == RULE
                              else '    ' + paint(ln))
                    if twin is not None:
                        for ln in _wrap(flow(twin['text'], flat), width, 18):
                            print(f'    {DIM}{ln}{OFF}' if ln == RULE
                                  else '    ' + GRN + paint(ln, GRN) + OFF)
            else:
                print(f'  {"src":<6}{DIM}(no PSP row matched this unit'
                      f' - run with --hunt to look for it){OFF}')
        print()
    more = len(todo) - (start + len(shown))
    if more > 0:
        print(f'{DIM}{more} more - next page: --start {start + len(shown)}{OFF}')


def main():
    args = sys.argv[1:]
    if not args or args[0] in ('-h', '--help', 'help'):
        print(__doc__)
        return
    cmd, rest = args[0], args[1:]
    if cmd in ('missing', 'view'):
        if '-h' in rest or '--help' in rest:
            print(MISSING_HELP)
            return
        opts = {'start': 0, 'limit': 0, 'pick': set(), 'flat': False,
                'ids': False, 'do_hunt': False}
        name = None
        want = {'--start': 'start', '--limit': 'limit'}
        i = 0
        while i < len(rest):
            a = rest[i]
            if a in want:
                if i + 1 == len(rest):
                    sys.exit(f'textview: {a} needs a number')
                opts[want[a]] = int(rest[i + 1])
                i += 2
            elif a.startswith('--start='):
                opts['start'] = int(a.split('=', 1)[1]); i += 1
            elif a.startswith('--limit='):
                opts['limit'] = int(a.split('=', 1)[1]); i += 1
            elif a == '--source':
                opts['pick'].update(('source known', 'source proven - no wording fits')); i += 1
            elif a == '--no-source':
                opts['pick'].add('no PSP source'); i += 1
            elif a == '--over':
                opts['pick'].add('over-cap draft'); i += 1
            elif a == '--flat':
                opts['flat'] = True; i += 1
            elif a == '--hunt':
                opts['do_hunt'] = True; i += 1
            elif a == '--ids':
                opts['ids'] = True; i += 1
            elif name is None and not a.startswith('-'):
                name = a; i += 1
            else:
                sys.exit(f'textview: {a}: unknown option\n\n{MISSING_HELP}')
        cmd_missing(name, **opts)
    elif cmd == 'file' and rest:
        cmd_file(rest[0])
    elif cmd == 'show' and len(rest) == 2:
        cmd_show(rest[0], rest[1])
    elif cmd == 'find' and rest:
        cmd_find(rest[0])
    elif cmd == 'gaps':
        cmd_gaps(rest[0] if rest else None)
    else:
        print(__doc__)
        sys.exit(2)


if __name__ == '__main__':
    main()
