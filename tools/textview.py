"""Text navigator: every text of a file with all of its sides at once.

  python tools/textview.py file D00/D00          a whole file
  python tools/textview.py show D00/D00 2        one item (id or pos)
  python tools/textview.py find "door is locked" search every side
  python tools/textview.py gaps [D00/D00]        targets without translation
  python tools/textview.py missing [FILE] ...    the untranslated strings,
                                                 browsable, with their Japanese

`missing` is the work view for the gaps (see its -h below): one entry per
untranslated target with the Japanese it came from laid out the way the
game breaks it, the PSP Japanese and PSP English whenever a source is
known, and the over-cap draft when one is parked in the manual note.
`--hunt` goes looking for a missing unit's Japanese inside the extracted
PSP trees by small identifiable fragments.

<name> is a PSX rel (D00/D00), a PSP rel (pack/dng/d00) or a file's bare
name (d00) - the sides of one file always show together:

  psx   Japanese as the PSX disc has it   (extracted_text/psx)
  jp    Japanese as the PSP disc has it   (extracted_text/psp_jp)
  us    English the PSP shipped, RAW - no reflow, no reflowed drafts
        (extracted_text/psp_us)
  trans the current translation (manual wins over generated; empty shows
        as empty) and the autogenerated one whenever it differs
  index ids, entry/box coordinates, byte positions, provenance, notes

Translation rows join their extracted row by `pos`; the three sides join
each other by the (entry, box) coordinate, translation/generated_mappings/align.tsv where
the boxes do not line up. A translation row's `psp` pointer is the row's
match into the PSP tree, so it is THE link for the units whose sides do
not share a file (SLPS_005.00 <-> EBOOT): the pointed-at rows fill the
jp/us sides on every region they resolve in. The PSP sides are SOURCES,
never targets of translation: a unit with no PSX row and no translation
row is source context only - `find` prints it, `gaps` never counts it.

A position is ONE unit: where a scan walked it twice the extract holds
two rows at the same `pos`, and the row that carries the translation
belongs to every one of them (they are flagged 'duplicate scan row')
rather than leaving a twin drawn as a gap no work queue can ever fill.
"""
import os
import re
import sys
import unicodedata
from collections import defaultdict

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(
    os.path.abspath(__file__))), 'src', 'injection_tools'))
import toolbelt   # noqa: E402

ROOT = toolbelt.ROOT
EXT = os.path.join(ROOT, 'data', 'extracted_text')
REGIONS = ('psx', 'psp_jp', 'psp_us')

TTY = sys.stdout.isatty() and not os.environ.get('NO_COLOR')
DIM = '\033[2m' if TTY else ''
BOLD = '\033[1m' if TTY else ''
REV = '\033[7m' if TTY else ''
RED = '\033[31m' if TTY else ''
GRN = '\033[32m' if TTY else ''
YLW = '\033[33m' if TTY else ''
OFF = '\033[0m' if TTY else ''

CODE_RE = re.compile(r'<FF[0-9A-F]{2}>')


