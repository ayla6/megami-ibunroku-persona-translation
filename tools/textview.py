def ext_rels(region):
    base = os.path.join(EXT, region)
    out = []
    for dirpath, _dirs, files in os.walk(base):
        for f in sorted(files):
            if f.endswith('.tsv'):
                rel = os.path.relpath(os.path.join(dirpath, f), base)[:-4]
                out.append(rel.replace(os.sep, '/'))
    return sorted(out)


_CACHE = {}


def sides_index():
    """{'e0': {'psx': 'ADV/E0', 'psp_jp': 'pack/E0', ...}} keyed by the
    file's bare name (case-insensitive: PSX D00/D00 <-> PSP pack/dng/d00)."""
    if 'index' not in _CACHE:
        idx = {}
        for region in REGIONS:
            for rel in ext_rels(region):
                key = rel.split('/')[-1].lower()
                slot = idx.setdefault(key, {})
                if region in slot:
                    slot.setdefault('clash', []).append(rel)
                slot[region] = rel
        _CACHE['index'] = idx
    return _CACHE['index']


def resolve(name):
    """-> (key, sides) for a name that is a rel, a bare file name, or either
    with a .tsv extension and any case ('D14', 'D14.tsv', 'D02/D14.tsv')."""
    idx = sides_index()
    key = name.split('/')[-1].lower()
    if key.endswith('.tsv'):
        key = key[:-4]
    if key not in idx:
        sys.exit(f'textview: {name}: no extracted text on any side '
                 f'(known: {len(idx)} files)')
    return key, idx[key]


def rows(region, rel):
    return toolbelt.read_extracted(region, rel, optional=True)


def trans_rows(rel):
    return (toolbelt.read_generated(rel, optional=True),
            toolbelt.read_manual(rel, optional=True))


def align_map(key):
    """{(entry, psx_box): (jp_box, us_box, kind)} from translation/generated_mappings."""
    path = os.path.join(toolbelt.MAPPINGS, 'align.tsv')
    out = {}
    if not os.path.exists(path):
        return out
    for line in open(path, encoding='utf-8').read().splitlines()[1:]:
        f = line.split('\t')
        if len(f) >= 6 and f[0].lower() == key:
            out[(f[1], f[2])] = (f[3], f[4], f[5])
    return out


class Item:
    """One unit of one file: its rows on every side."""

    def __init__(self, entry, box):
        self.entry, self.box = entry, box
        self.psx = self.jp = self.us = None
        self.gen = self.man = None
        self.kind = ''

    @property
    def pos(self):
        for r in (self.psx, self.us, self.jp):
            if r:
                return r['pos']
        return (self.gen or self.man or {}).get('pos', '')

    @property
    def trans(self):
        """Current translation: a human's manual en wins over the auto one."""
        if self.man and (self.man.get('en') or '').strip():
            return self.man['en']
        return (self.gen or {}).get('en', '') or ''

    @property
    def auto(self):
        return (self.gen or {}).get('en', '') or ''

    @property
    def note(self):
        return (self.man or {}).get('note', '') or ''

    @property
    def target(self):
        """True for a unit the PSX disc shows: it has a PSX row, or a
        translation row to build at its pos. A unit that lives only on
        the PSP sides is source material - it is never translated, so it
        is never counted as translated or not."""
        return bool(self.psx or self.gen or self.man)


def shared_entries(*row_lists):
    """{entry} whose (entry, box) coordinate is really shared: every side
    holds the same box set for it. The cross-side coordinate is a contract
    (docs/TEXT_ARCHITECTURE.md) and most files honour it - but where the
    scans drifted (EBOOT: 19262 JP rows vs 4490 US rows) a same-numbered
    row is NOT the same unit and must never be shown as its twin."""
    sets = {}
    for rows_ in row_lists:
        by = {}
        for r in rows_:
            by.setdefault(r['entry'], set()).add(r['box'])
        for e, s in by.items():
            sets.setdefault(e, []).append(s)
    return {e for e, ss in sets.items() if all(s == ss[0] for s in ss)}


def build_items(psx_rel, jp_rel, us_rel):
    """Join the three sides by (entry, box) - align.tsv where the boxes do
    not line up - and the translation rows by pos. A translation row's
    `psp` pointer is its match into the PSP tree, so the rows it names are
    the unit's jp/us sides wherever those sides have no joined row.
    Unmatched rows keep their own item (that is what the viewer is for)."""
    key = psx_rel.split('/')[-1].lower() if psx_rel else ''
    amap = align_map(key)
    items, by_key = [], {}

    def slot(entry, box):
        k = (entry, box)
        if k not in by_key:
            by_key[k] = Item(entry, box)
            items.append(by_key[k])
        return by_key[k]

    psx_rows = rows('psx', psx_rel) if psx_rel else []
    jp_rows = {(r['entry'], r['box']): r for r in rows('psp_jp', jp_rel)} if jp_rel else {}
    us_rows = {(r['entry'], r['box']): r for r in rows('psp_us', us_rel)} if us_rel else {}
    shared = shared_entries(psx_rows, list(jp_rows.values()), list(us_rows.values()))
    for r in psx_rows:
        it = slot(r['entry'], r['box'])
        it.psx = r
        jb, ub, _kind = amap.get((r['entry'], r['box']), (r['box'], r['box'], ''))
        if (r['entry'], r['box']) in amap or r['entry'] in shared:
            it.jp = jp_rows.pop((r['entry'], jb), None)
            it.us = us_rows.pop((r['entry'], ub), None)
        it.kind = amap.get((r['entry'], r['box']), (None, None, ''))[2]
    for side, rowset in (('jp', jp_rows), ('us', us_rows)):
        for r in rowset.values():
            if r['entry'] in shared:
                it = slot(r['entry'], r['box'])
                if side == 'jp':
                    it.jp = it.jp or r
                else:
                    it.us = it.us or r
                it.kind = it.kind or 'psp-only'
            else:
                orphan = Item(r['entry'], r['box'])
                if side == 'jp':
                    orphan.jp = r
                else:
                    orphan.us = r
                orphan.kind = 'psp-only (unpaired side)'
                items.append(orphan)

    gen, man = trans_rows(psx_rel) if psx_rel else ([], [])
    by_pos = {}
    for it in items:
        by_pos.setdefault(it.pos, []).append(it)
    for pos, group in by_pos.items():       # one scan walked the unit twice
        if pos and len(group) > 1:
            for it in group:
                it.kind = (it.kind + ' duplicate scan row').strip()
    for src, attr in ((gen, 'gen'), (man, 'man')):
        for r in src:
            hit = by_pos.get(r['pos'])
            if hit:
                # a position is ONE unit: when a scan walked it twice the
                # extract holds two rows at the same pos, and the row that
                # carries the translation belongs to every one of them -
                # otherwise the twin is drawn as a gap that no work queue
                # can ever fill
                for it in hit:
                    setattr(it, attr, r)
            else:
                it = Item('', '')
                setattr(it, attr, r)
                it.kind = 'orphan row'
                items.append(it)
    for it in items:                       # the match: psp pointer -> sides
        for r in (it.gen, it.man):
            if not (r and r.get('psp')):
                continue
            for region, row in psp_rows(r['psp'], it.entry):
                if region == 'psp_jp':
                    it.jp = it.jp or row
                else:
                    it.us = it.us or row
    items.sort(key=lambda it: (str(it.entry), int(it.box) if str(it.box).isdigit() else 0))
    return items


