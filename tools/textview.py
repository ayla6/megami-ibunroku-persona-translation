def paint(t, base=None):
    """Raw text with the control codes dimmed (never rewritten). `base` is
    the colour the code's dim ends back into, so a line can be tinted and
    still show its structure."""
    back = OFF if base is None else base
    return CODE_RE.sub(lambda m: f'{DIM}{m.group(0)}{back}', t)


def n_boxes(t):
    """Textboxes of a message: <FF04> is the box break, so pages = 1+FF04."""
    return t.count('<FF04>') + 1


def side_line(label, r, color=''):
    if r is None:
        return f'  {label:<7}{DIM}(no row on this side){OFF}'
    mark = f' {color}●{OFF}' if color else ''
    return (f'  {label:<7}{mark} {DIM}{r["pos"]:<10}{OFF} {paint(r["text"])}')


def psp_rel(name):
    """The psp-side extract rel behind a psp-pointer name."""
    if name.startswith('pack/'):
        return name
    if re.fullmatch(r'd[0-9a-f]{2}m?', name):
        return 'pack/dng/' + name
    if re.fullmatch(r'e[0-9]', name, re.I):
        return 'pack/' + name.upper()
    if name.upper() in ('EBOOT', 'BOOT'):
        return 'EBOOT'
    return 'pack/talk/' + name.upper()


_SRC = {}


def _off(pos):
    """The byte offset of a pos cell ('0x28b5e2' or '0:0x15f0')."""
    return int(pos.split(':')[-1], 16)


def _src_index(region, rel):
    """{(form, key): row} of one extract - the three locator forms a `psp`
    pointer may carry: the unit's byte position (`pos`), its unit id (`id`)
    and its (entry, box) coordinate (`unit`; talk answer pointers name the
    answer slot, entry 1). Rows are kept position-sorted for the
    containing-unit lookup below."""
    key = (region, rel)
    if key not in _SRC:
        idx = {}
        rows = []
        for r in (toolbelt.read_extracted(region, rel, optional=True) or []):
            idx.setdefault(('pos', r['pos']), r)
            idx.setdefault(('id', r['id']), r)
            idx.setdefault(('unit', (r['entry'], r['box'])), r)
            rows.append(r)
        rows.sort(key=lambda r: _off(r['pos']))
        idx['@rows'] = rows
        _SRC[key] = idx
    return _SRC[key]


def _covering(idx, off):
    """The row whose unit holds `off` (its span runs to the next row's
    start). A `psp` pointer may name the first decoded unit of a unit
    that starts earlier - the unit is the source, whichever byte of it
    the pointer names."""
    rows = idx['@rows']
    lo, hi = 0, len(rows)
    while lo < hi:
        mid = (lo + hi) // 2
        if _off(rows[mid]['pos']) <= off:
            lo = mid + 1
        else:
            hi = mid
    return rows[lo - 1] if lo else None


def psp_rows(psp, entry=''):
    """[(region, row)] the source rows a translation row's `psp` pointer
    names - THE match of the row into the PSP tree ('EBOOT:26b7c0',
    'E2:127', 'KOUMAN:36cc'; comma-separated for a row derived from
    several units). A unit index is the shared cross-side coordinate and
    answers on every side; a byte position answers only in the region
    whose layout it came from. Where both answer but name different units
    (a drifted extract), only the US row - the ported wording's source -
    is the match; the Japanese twin is not shown, because a same-numbered
    unit in a drifted extract is NOT the source and must never mislead."""
    out = []
    for p in psp.split(','):
        out += _psp_rows_one(p.strip(), entry)
    return out


_PAIRS = {}


def pair_map(direction):
    """{pos: other pos} - the verified PSP-US <-> PSP-JP unit pairs
    (src/extraction_tools/matching/boot_pairs.py), one map per direction:
    a byte position is a slot in ONE build's layout and can be a US slot
    in one pair and a JP slot in another, so the directions never share a
    key space. Only verified pairs are here - where a matcher did not
    prove the twin, there is no twin to show."""
    if not _PAIRS:
        us_jp, jp_us = {}, {}
        path = os.path.join(toolbelt.MAPPINGS, 'psp_pairs.tsv')
        if os.path.exists(path):
            for line in open(path, encoding='utf-8').read().splitlines()[1:]:
                f = line.split('\t')
                if len(f) >= 3:
                    us_jp[f[1]] = f[2]
                    jp_us[f[2]] = f[1]
        _PAIRS['us_jp'], _PAIRS['jp_us'] = us_jp, jp_us
    return _PAIRS[direction]


def _paired(name, rel, region, pos):
    other = pair_map('us_jp' if region == 'psp_jp' else 'jp_us').get(pos)
    return _src_index(region, rel).get(('pos', other)) if other else None


def _psp_rows_one(psp, entry):
    if not psp or ':' not in psp:
        return []
    name, locator = psp.split(':', 1)      # left split: archive locators are 'entry:0xoffset'
    rel = psp_rel(name)
    # A locator is the unit's byte position or its unit index - and a
    # digit-only one ('265860') is legal in both readings, so both are
    # candidates and only the extract decides. The unit index is the
    # shared cross-side coordinate and wins where it names a row.
    cands = [('pos', locator)]
    if re.fullmatch(r'[0-9]+', locator):
        cands += [('unit', (entry, locator)), ('id', locator),
                  ('pos', hex(int(locator, 10))), ('pos', hex(int(locator, 16)))]
    else:
        cands.append(('pos', locator.lower()))
        if re.fullmatch(r'[0-9a-fA-F]+', locator):
            cands.append(('pos', '0x' + locator.lower()))

    def hit(region):
        idx = _src_index(region, rel)
        for c in cands:
            if c in idx:
                return idx[c]
        # a hex offset may name a byte INSIDE its unit (a unit starts at
        # its first decoded unit); a digit-only locator is ambiguous (a
        # unit index reads as a hex offset too), so accept a containing
        # unit only when exactly one reading finds one
        offs = []
        if re.fullmatch(r'[0-9a-fA-F]+', locator):
            offs.append(int(locator, 16))
        if locator.isdigit():
            offs.append(int(locator, 10))
        for off in offs:                 # offsets are written as hex
            row = _covering(idx, off)    # ('%x'), unit ids never reach here
            if row is not None:          # (their exact forms hit first)
                return row
        return None
    us, jp = hit('psp_us'), hit('psp_jp')
    if us and jp and (jp['entry'], jp['box']) != (us['entry'], us['box']):
        jp = None          # same-numbered row of a drifted scan: not the twin
    keys = []
    if re.fullmatch(r'[0-9a-fA-F]+', locator):
        keys.append(hex(int(locator, 16)))
    if locator.isdigit():
        keys.append(hex(int(locator, 10)))
    for k in keys:                    # the verified pair map: the twin of
        if us and jp:                 # a byte position is not guessable,
            break                     # so it is shown only where a matcher
        if not us:                    # proved it
            us = _paired(name, rel, 'psp_us', k)
        if not jp:
            jp = _paired(name, rel, 'psp_jp', k)
    return ([('psp_us', us)] if us else []) + ([('psp_jp', jp)] if jp else [])


def psp_source(psp, entry=''):
    """[(region, text)] at a row's psp pointer: the source text the row
    was derived from. Always shown, so a row's provenance is visible even
    where the side has no row."""
    return [(region, r['text']) for region, r in psp_rows(psp, entry)]


def render(it, title=''):
    out = []
    head = title or f'entry {it.entry or "-"} box {it.box}'
    kinds = f' {DIM}[{it.kind}]{OFF}' if getattr(it, 'kind', '') else ''
    out.append(f'{BOLD}{REV} {head} {OFF}{kinds}')
    out.append(side_line('psx', it.psx))
    out.append(side_line('jp', it.jp))
    out.append(side_line('us', it.us, GRN))
    boxes = []
    for label, r in (('psx', it.psx), ('jp', it.jp), ('us', it.us)):
        if r:
            boxes.append(f'{label} {n_boxes(r["text"])}')
    if boxes:
        least = min(n_boxes(r['text']) for r in (it.psx, it.jp, it.us) if r)
        out.append(f'  {"boxes":<7}{DIM}{" · ".join(boxes)}  ->  least {least}{OFF}')
    trans = it.trans
    if trans.strip():
        who = 'manual' if (it.man and (it.man.get("en") or "").strip()) else 'generated'
        out.append(f'  {"trans":<7}{YLW}●{OFF} {DIM}({who}){OFF} {paint(trans)}')
    elif it.target:
        out.append(f'  {"trans":<7}{RED}(empty){OFF}')
    else:
        out.append(f'  {"trans":<7}{DIM}(source, not a target){OFF}')
    if it.auto.strip() and it.auto != trans:
        out.append(f'  {"auto":<7}{DIM}(superseded by the above){OFF} {paint(it.auto)}')
    if it.note:
        out.append(f'  {"note":<7}{RED}{it.note}{OFF}')
    srcs = []
    shown = {r['text'] for r in (it.psx, it.jp, it.us) if r}
    for r in (it.gen, it.man):
        if r and r.get('psp'):
            for region, text in psp_source(r['psp'], it.entry):
                if text in shown:        # already visible as a joined side row
                    continue
                line = f'{region[4:]:<3} {r["psp"]:<14} {paint(text)}'
                if line not in srcs:
                    srcs.append(line)
    for line in srcs:
        out.append(f'  {"src":<7}{DIM}{line}{OFF}')
    ids = []
    for label, r in (('psx', it.psx), ('jp', it.jp), ('us', it.us)):
        if r:
            ids.append(f'{label} id {r["id"]} entry {r["entry"] or "-"} box {r["box"]}')
    for label, r in (('gen', it.gen), ('man', it.man)):
        if r:
            ids.append(f'{label} id {r["id"]} pos {r["pos"]}'
                       + (f' psp {r["psp"]}' if r.get('psp') else ''))
    if ids:
        out.append(f'  {"index":<7}{DIM}{" | ".join(ids)}{OFF}')
    return '\n'.join(out)


